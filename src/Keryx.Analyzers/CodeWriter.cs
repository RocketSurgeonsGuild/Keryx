using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Keryx.Analyzers;

/// <summary>
///     Writes a generated source file as text, line by line, with the layout every Keryx generator gives its output (ADR 0001, Incremental
///     generation rules): four spaces per level, <c>\n</c> line endings on every platform (so the output is deterministic), a blank line
///     between the members of a type unless both are fields without attributes (<see cref="Member" />), a blank line after a statement that
///     ends with a block when another statement follows (<see cref="CloseStatement" />), a break after <c>=&gt;</c> with the body one level
///     deeper (<see cref="Arrow" />), a constructor's parameters one per line when it has more than one (<see cref="Parameters" />), and
///     preprocessor directives at column 0 (<see cref="Directive" />).
/// </summary>
/// <remarks>
///     The emitters write C# text: names and types come from the models' fully qualified (<c>global::</c>) strings, which are written as they
///     are, and an expression is a string built where it is used. Nothing parses, builds or normalizes syntax (OQ-71; Roslyn's
///     <c>SyntaxFactory</c> was tried and rejected for generator time). A writer is created inside <c>RegisterSourceOutput</c>, for one
///     file; incremental models never hold one.
/// </remarks>
internal sealed class CodeWriter
{
    /// <summary>
    ///     Generated code names the user's request, response, service and handler types only because the user declared a handler for them,
    ///     so a deprecated (<c>[Obsolete]</c>) one must not turn into CS0612/CS0618 in a generated file, which the user cannot suppress at
    ///     their own source.
    /// </summary>
    public const string ObsoletePragma = "#pragma warning disable CS0612, CS0618";

    /// <summary><c>[MethodImpl(MethodImplOptions.NoInlining)]</c>.</summary>
    public const string NoInliningAttribute =
        "[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]";

    /// <summary><c>[MethodImpl(MethodImplOptions.AggressiveInlining)]</c>.</summary>
    public const string AggressiveInliningAttribute =
        "[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]";

    /// <summary><c>[AsyncMethodBuilder(typeof(PoolingAsyncValueTaskMethodBuilder))]</c>.</summary>
    public const string PoolingBuilderAttribute =
        "[global::System.Runtime.CompilerServices.AsyncMethodBuilder(typeof(global::System.Runtime.CompilerServices.PoolingAsyncValueTaskMethodBuilder))]";

    private const string Indentation = "    ";

    /// <summary>The indentation of each depth, built once.</summary>
    private static readonly string[] Indents = [.. Enumerable.Range(0, 16).Select(static depth => string.Concat(Enumerable.Repeat(Indentation, depth)))];

    private readonly StringBuilder _builder;

    /// <summary>The member state of each enclosing block, saved by <see cref="Open" /> and restored by <see cref="Close" />.</summary>
    private readonly Stack<MemberKind> _enclosing = new();

    private int _depth;
    private MemberKind _previousMember;
    private bool _blankLine;

    /// <summary>Starts a file with the header: <c>// &lt;auto-generated/&gt;</c>, <c>#nullable enable</c> and the pragma, then a blank line.</summary>
    /// <param name="pragma">The header's <c>#pragma warning disable</c> line: <see cref="ObsoletePragma" /> unless given; none when <see langword="null" />.</param>
    /// <param name="capacity">The initial capacity of the text.</param>
    public CodeWriter(string? pragma = ObsoletePragma, int capacity = 4096)
    {
        _builder = new(capacity);
        _builder.Append("// <auto-generated/>\n#nullable enable\n");
        if (pragma is not null)
        {
            _builder.Append(pragma).Append('\n');
        }

        _builder.Append('\n');
    }

    /// <summary>What kind of member was written last in a type body, for the blank line between members.</summary>
    private enum MemberKind : byte
    {
        None,
        PlainField,
        Other,
    }

    /// <summary>The version in <c>[GeneratedCode("Keryx", version)]</c>.</summary>
    public static string Version { get; } = typeof(CodeWriter).Assembly.GetName().Version?.ToString() ?? "1.0.0";

    /// <summary><c>[GeneratedCode("Keryx", version)]</c>, written on generated members and on the types Keryx owns.</summary>
    public static string GeneratedCodeAttribute { get; } = $"[global::System.CodeDom.Compiler.GeneratedCode({Literal("Keryx")}, {Literal(Version)})]";

    /// <summary>The depth of the next line: the number of blocks open.</summary>
    public int Depth => _depth;

    /// <summary>A C# string literal of <paramref name="value" />, quoted and escaped.</summary>
    public static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    /// <summary>
    ///     Writes one line at the current depth. A blank line goes before it when the statement before it ended with a block
    ///     (<see cref="CloseStatement" />).
    /// </summary>
    public void Line(string text)
    {
        if (_blankLine)
        {
            _builder.Append('\n');
            _blankLine = false;
        }

        _builder.Append(Indent(_depth)).Append(text).Append('\n');
    }

    /// <summary>Writes an empty line, without indentation.</summary>
    public void Line()
    {
        _blankLine = false;
        _builder.Append('\n');
    }

    /// <summary>Writes a preprocessor directive (<c>#nullable disable warnings</c>) at column 0, after the pending blank line if any.</summary>
    public void Directive(string text)
    {
        if (_blankLine)
        {
            _builder.Append('\n');
            _blankLine = false;
        }

        _builder.Append(text).Append('\n');
    }

    /// <summary>Writes one <c>///</c> documentation line per entry, at the current depth, as given (XML, with <c>&lt;</c> escaped in text).</summary>
    public void Documentation(params string[] lines)
    {
        foreach (var line in lines)
        {
            Line("/// " + line);
        }
    }

    /// <summary>
    ///     Starts the next member of a type (or of a namespace): a blank line before it unless it is the first, or it and the member before it
    ///     are both fields without attributes. Call it before the member's documentation.
    /// </summary>
    /// <param name="plainField">Whether the member is a field without attributes (documentation does not count).</param>
    public void Member(bool plainField = false)
    {
        var kind = plainField ? MemberKind.PlainField : MemberKind.Other;
        if (_previousMember != MemberKind.None && !( _previousMember == MemberKind.PlainField && kind == MemberKind.PlainField ))
        {
            Line();
        }

        _previousMember = kind;
    }

    /// <summary><c>{</c> on its own line; the lines after it are one level deeper.</summary>
    public void Open()
    {
        Line("{");
        _enclosing.Push(_previousMember);
        _previousMember = MemberKind.None;
        _depth++;
    }

    /// <summary><c>}</c> on its own line, one level less deep: the end of a type, a member's body or a block that does not end a statement.</summary>
    public void Close()
    {
        _blankLine = false;
        _depth--;
        _previousMember = _enclosing.Pop();
        Line("}");
    }

    /// <summary>
    ///     <see cref="Close" /> for the block that ends a statement (an <c>if</c>, <c>try</c>/<c>catch</c>, <c>foreach</c> or <c>switch</c>): when
    ///     another statement follows in the same block, a blank line goes before it.
    /// </summary>
    public void CloseStatement()
    {
        Close();
        _blankLine = true;
    }

    /// <summary><c>namespace name {</c>.</summary>
    public void Namespace(string name)
    {
        Line("namespace " + name);
        Open();
    }

    /// <summary>
    ///     A member with an expression body: <c>declaration =&gt;</c> ends the line, and <paramref name="body" /> is on the next line, one level
    ///     deeper, with its <c>;</c>.
    /// </summary>
    public void Arrow(string declaration, string body)
    {
        Line(declaration + " =>");
        _depth++;
        Line(body + ";");
        _depth--;
    }

    /// <summary>
    ///     A member with an expression body written with nullable warnings disabled (OQ-58): after <c>declaration =&gt;</c>, a blank line,
    ///     <c>#nullable disable warnings</c> and <paramref name="body" /> at the depth of the declaration. That is the layout the generator has
    ///     always written for this body. The type that holds the member restores the warnings before its closing brace
    ///     (<c>#nullable restore warnings</c>, <see cref="Directive" />).
    /// </summary>
    public void NullableObliviousArrow(string declaration, string body)
    {
        Line(declaration + " =>");
        Line();
        Directive("#nullable disable warnings");
        Line(body + ";");
    }

    /// <summary>
    ///     <c>head(parameters)</c>: on one line with at most one parameter, else <c>head(</c> and each parameter on its own line one level
    ///     deeper, the last one ending with <c>)</c>.
    /// </summary>
    public void Parameters(string head, IReadOnlyList<string> parameters)
    {
        if (parameters.Count < 2)
        {
            Line(parameters.Count == 0 ? head + "()" : head + "(" + parameters[0] + ")");
            return;
        }

        Line(head + "(");
        _depth++;
        for (var i = 0; i < parameters.Count; i++)
        {
            Line(i < parameters.Count - 1 ? parameters[i] + "," : parameters[i] + ")");
        }

        _depth--;
    }

    /// <summary><c>switch (governing) {</c>; each <see cref="Section" /> follows, then <see cref="CloseStatement" />.</summary>
    public void Switch(string governing)
    {
        Line("switch (" + governing + ")");
        Open();
    }

    /// <summary>One switch section: <paramref name="label" /> (<c>case X x:</c>, <c>default:</c>) and its one statement, one level deeper.</summary>
    public void Section(string label, string statement)
    {
        Line(label);
        _depth++;
        Line(statement);
        _depth--;
    }

    /// <summary>The source text of the file: UTF-8, as written.</summary>
    public SourceText ToSourceText() => SourceText.From(_builder.ToString(), Encoding.UTF8);

    public override string ToString() => _builder.ToString();

    private static string Indent(int depth) => depth < Indents.Length ? Indents[depth] : string.Concat(Enumerable.Repeat(Indentation, depth));
}
