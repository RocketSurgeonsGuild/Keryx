using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace Keryx.Analyzers;

/// <summary>
///     What the emitters share to build generated sources with Roslyn's <see cref="SyntaxFactory" />, the way Dovetail's generators do: names
///     and types from the models' fully qualified (<c>global::</c>) strings, the attributes and documentation comments Keryx writes, and
///     <see cref="Render" />, which normalizes the whitespace of a compilation unit once and adds its header last. Syntax is built only inside
///     <c>RegisterSourceOutput</c>: incremental models carry strings, never syntax.
/// </summary>
internal static class GeneratedSyntax
{
    /// <summary>
    ///     Generated code names the user's request, response, service and handler types only because the user declared a handler for them,
    ///     so a deprecated (<c>[Obsolete]</c>) one must not turn into CS0612/CS0618 in a generated file, which the user cannot suppress at
    ///     their own source.
    /// </summary>
    public const string ObsoletePragma = "#pragma warning disable CS0612, CS0618";

    /// <summary>
    ///     The header pragma of the mediator: <see cref="ObsoletePragma" /> and CS9113. Every link takes the pipeline context and the message
    ///     (ADR 0001, Generated pipeline shape), and the last link does not read the context when the handler's invoker is static, nor either
    ///     of them when a notification type has no handlers. An unread primary constructor parameter is not captured, so the link holds only
    ///     what it reads, but it is warning CS9113, an error under warnings-as-errors in the user's project.
    /// </summary>
    public const string MediatorPragma = "#pragma warning disable CS0612, CS0618, CS9113";

    private const string LineFeed = "\n";

    /// <summary>The version in <c>[GeneratedCode("Keryx", version)]</c>.</summary>
    public static string Version { get; } = typeof(GeneratedSyntax).Assembly.GetName().Version?.ToString() ?? "1.0.0";

    /// <summary>
    ///     The source text of a generated file: <paramref name="unit" /> with its whitespace normalized once (four spaces per level,
    ///     <c>\n</c> line endings on every platform, so the output is deterministic), blank lines between the members of a type that are not
    ///     both fields, and then the header (<c>// &lt;auto-generated/&gt;</c>, <c>#nullable enable</c> and, unless it is
    ///     <see langword="null" />, <paramref name="pragma" />) added before everything else.
    /// </summary>
    /// <param name="unit">The compilation unit, without header trivia.</param>
    /// <param name="pragma">The header's <c>#pragma warning disable</c> line: <see cref="ObsoletePragma" /> unless given.</param>
    public static SourceText Render(CompilationUnitSyntax unit, string? pragma = ObsoletePragma)
    {
        var normalized = (CompilationUnitSyntax)new Layout().Visit(unit.NormalizeWhitespace("    ", LineFeed));
        var header = ParseLeadingTrivia($"// <auto-generated/>{LineFeed}#nullable enable{LineFeed}{( pragma is null ? "" : pragma + LineFeed )}{LineFeed}");
        var rendered = normalized.WithLeadingTrivia(header.AddRange(normalized.GetLeadingTrivia()));
        return SourceText.From(rendered.ToFullString() + LineFeed, Encoding.UTF8);
    }

    /// <summary>A type from its C# text (fully qualified, with nullable annotations).</summary>
    public static TypeSyntax TypeName(string text) => ParseTypeName(text);

    /// <summary>A name from its C# text (fully qualified).</summary>
    public static NameSyntax Qualified(string text) => ParseName(text);

    /// <summary>An expression from its C# text: a default value or a service key, which the models hold as C# expressions.</summary>
    public static ExpressionSyntax Code(string text) => ParseExpression(text);

    public static IdentifierNameSyntax Id(string name) => IdentifierName(name);

    public static LiteralExpressionSyntax Number(int value) => LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(value));

    /// <summary>An <c>int</c> constant, negative ones as a unary minus.</summary>
    public static ExpressionSyntax Integer(int value) =>
        value >= 0 ? Number(value) : ParseExpression(value.ToString(CultureInfo.InvariantCulture));

    public static LiteralExpressionSyntax StringLiteral(string value) => LiteralExpression(SyntaxKind.StringLiteralExpression, Literal(value));

    public static LiteralExpressionSyntax DefaultLiteral() => LiteralExpression(SyntaxKind.DefaultLiteralExpression, Token(SyntaxKind.DefaultKeyword));

    public static LiteralExpressionSyntax NullLiteral() => LiteralExpression(SyntaxKind.NullLiteralExpression);

    public static LiteralExpressionSyntax BooleanLiteral(bool value) =>
        LiteralExpression(value ? SyntaxKind.TrueLiteralExpression : SyntaxKind.FalseLiteralExpression);

    public static SyntaxTokenList Modifiers(params SyntaxKind[] kinds) => TokenList(kinds.Select(Token));

    public static MemberAccessExpressionSyntax Member(ExpressionSyntax target, string name) => Member(target, IdentifierName(name));

    public static MemberAccessExpressionSyntax Member(ExpressionSyntax target, SimpleNameSyntax name) =>
        MemberAccessExpression(SyntaxKind.SimpleMemberAccessExpression, target, name);

    public static GenericNameSyntax Generic(string name, params TypeSyntax[] arguments) =>
        GenericName(Identifier(name)).WithTypeArgumentList(TypeArgumentList(SeparatedList(arguments)));

    public static InvocationExpressionSyntax Invoke(ExpressionSyntax target, params ExpressionSyntax[] arguments) =>
        Invoke(target, arguments.Select(Argument));

    public static InvocationExpressionSyntax Invoke(ExpressionSyntax target, IEnumerable<ArgumentSyntax> arguments) =>
        InvocationExpression(target, ArgumentList(SeparatedList(arguments)));

    /// <summary>A <c>ref</c> argument.</summary>
    public static ArgumentSyntax RefArgument(ExpressionSyntax expression) => Argument(expression).WithRefKindKeyword(Token(SyntaxKind.RefKeyword));

    /// <summary>An <c>out var name</c> argument.</summary>
    public static ArgumentSyntax OutVarArgument(string name) =>
        Argument(DeclarationExpression(IdentifierName("var"), SingleVariableDesignation(Identifier(name)))).WithRefKindKeyword(Token(SyntaxKind.OutKeyword));

    public static ParameterSyntax Param(TypeSyntax type, string name, ExpressionSyntax? defaultValue = null)
    {
        var parameter = Parameter(Identifier(name)).WithType(type);
        return defaultValue is null ? parameter : parameter.WithDefault(EqualsValueClause(defaultValue));
    }

    public static ParameterListSyntax Params(params ParameterSyntax[] parameters) => ParameterList(SeparatedList(parameters));

    public static ExpressionStatementSyntax Assign(ExpressionSyntax target, ExpressionSyntax value) =>
        ExpressionStatement(AssignmentExpression(SyntaxKind.SimpleAssignmentExpression, target, value));

    public static ExpressionStatementSyntax Call(ExpressionSyntax target, params ExpressionSyntax[] arguments) => ExpressionStatement(Invoke(target, arguments));

    public static ReturnStatementSyntax Return(ExpressionSyntax expression) => ReturnStatement(expression);

    /// <summary><c>typeof(type)</c>.</summary>
    public static TypeOfExpressionSyntax TypeOf(string type) => TypeOfExpression(ParseTypeName(type));

    public static BinaryExpressionSyntax Equal(ExpressionSyntax left, ExpressionSyntax right) => BinaryExpression(SyntaxKind.EqualsExpression, left, right);

    public static BinaryExpressionSyntax NotEqual(ExpressionSyntax left, ExpressionSyntax right) =>
        BinaryExpression(SyntaxKind.NotEqualsExpression, left, right);

    public static BinaryExpressionSyntax Coalesce(ExpressionSyntax left, ExpressionSyntax right) =>
        BinaryExpression(SyntaxKind.CoalesceExpression, left, right);

    /// <summary>A target-typed <c>new(arguments)</c>.</summary>
    public static ImplicitObjectCreationExpressionSyntax TargetTypedNew(params ExpressionSyntax[] arguments) =>
        ImplicitObjectCreationExpression(ArgumentList(SeparatedList(arguments.Select(Argument))), null);

    public static ObjectCreationExpressionSyntax New(TypeSyntax type, params ExpressionSyntax[] arguments) =>
        ObjectCreationExpression(type).WithArgumentList(ArgumentList(SeparatedList(arguments.Select(Argument))));

    public static CastExpressionSyntax Cast(TypeSyntax type, ExpressionSyntax expression) => CastExpression(type, expression);

    /// <summary><c>expression!</c>.</summary>
    public static PostfixUnaryExpressionSyntax NotNull(ExpressionSyntax expression) =>
        PostfixUnaryExpression(SyntaxKind.SuppressNullableWarningExpression, expression);

    /// <summary><c>var name = value;</c>.</summary>
    public static LocalDeclarationStatementSyntax Var(string name, ExpressionSyntax value) => Local(IdentifierName("var"), name, value);

    public static LocalDeclarationStatementSyntax Local(TypeSyntax type, string name, ExpressionSyntax? value = null)
    {
        var declarator = VariableDeclarator(Identifier(name));
        return LocalDeclarationStatement(
            VariableDeclaration(type, SingletonSeparatedList(value is null ? declarator : declarator.WithInitializer(EqualsValueClause(value))))
        );
    }

    public static FieldDeclarationSyntax Field(SyntaxTokenList modifiers, TypeSyntax type, string name, ExpressionSyntax? initializer = null)
    {
        var declarator = VariableDeclarator(Identifier(name));
        return FieldDeclaration(
                VariableDeclaration(type, SingletonSeparatedList(initializer is null ? declarator : declarator.WithInitializer(EqualsValueClause(initializer))))
            )
           .WithModifiers(modifiers);
    }

    public static MethodDeclarationSyntax Method(SyntaxTokenList modifiers, TypeSyntax returnType, string name, ParameterListSyntax parameters) =>
        MethodDeclaration(returnType, Identifier(name)).WithModifiers(modifiers).WithParameterList(parameters);

    /// <summary>The method with an expression body.</summary>
    public static MethodDeclarationSyntax Expression(this MethodDeclarationSyntax method, ExpressionSyntax body) =>
        method.WithExpressionBody(ArrowExpressionClause(body)).WithSemicolonToken(Token(SyntaxKind.SemicolonToken));

    /// <summary>The method with a block body.</summary>
    public static MethodDeclarationSyntax Statements(this MethodDeclarationSyntax method, IEnumerable<StatementSyntax> statements) =>
        method.WithBody(Block(statements));

    /// <summary>
    ///     <c>governing switch { arms }</c>. Each arm is on its own line, and the last one ends with no comma, after whitespace
    ///     normalization.
    /// </summary>
    public static SwitchExpressionSyntax SwitchOn(ExpressionSyntax governing, IEnumerable<SwitchExpressionArmSyntax> arms) =>
        SwitchExpression(governing, SeparatedList(arms));

    /// <summary>An arm <c>_ when guard =&gt; result</c>: the guard alone selects it.</summary>
    public static SwitchExpressionArmSyntax WhenArm(ExpressionSyntax guard, ExpressionSyntax result) =>
        SwitchExpressionArm(DiscardPattern(), WhenClause(guard), result);

    /// <summary>An arm <c>constant =&gt; result</c>.</summary>
    public static SwitchExpressionArmSyntax ConstantArm(int constant, ExpressionSyntax result) => SwitchExpressionArm(ConstantPattern(Number(constant)), result);

    /// <summary>The arm <c>_ =&gt; result</c>.</summary>
    public static SwitchExpressionArmSyntax DiscardArm(ExpressionSyntax result) => SwitchExpressionArm(DiscardPattern(), result);

    /// <summary>A switch section <c>case var _ when guard: statement</c>: the guard alone selects it.</summary>
    public static SwitchSectionSyntax WhenSection(ExpressionSyntax guard, StatementSyntax statement) =>
        SwitchSection(
            SingletonList<SwitchLabelSyntax>(CasePatternSwitchLabel(VarPattern(DiscardDesignation()), WhenClause(guard), Token(SyntaxKind.ColonToken))),
            SingletonList(statement)
        );

    /// <summary>A switch section <c>case constant: statement</c>.</summary>
    public static SwitchSectionSyntax ConstantSection(int constant, StatementSyntax statement) =>
        SwitchSection(SingletonList<SwitchLabelSyntax>(CaseSwitchLabel(Number(constant))), SingletonList(statement));

    /// <summary>One attribute in its own list: <c>[name(arguments)]</c>.</summary>
    public static AttributeListSyntax AttributeOf(string name, params AttributeArgumentSyntax[] arguments)
    {
        var attribute = Attribute(ParseName(name));
        return AttributeList(SingletonSeparatedList(arguments.Length == 0 ? attribute : attribute.WithArgumentList(AttributeArgumentList(SeparatedList(arguments)))));
    }

    /// <summary><c>[GeneratedCode("Keryx", version)]</c>, written on generated members and on the types Keryx owns.</summary>
    public static AttributeListSyntax GeneratedCodeAttribute() =>
        AttributeOf("global::System.CodeDom.Compiler.GeneratedCode", AttributeArgument(StringLiteral("Keryx")), AttributeArgument(StringLiteral(Version)));

    /// <summary><c>[MethodImpl(MethodImplOptions.NoInlining)]</c>.</summary>
    public static AttributeListSyntax NoInliningAttribute() =>
        AttributeOf(
            "global::System.Runtime.CompilerServices.MethodImpl",
            AttributeArgument(ParseName("global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining"))
        );

    /// <summary><c>[AsyncMethodBuilder(typeof(PoolingAsyncValueTaskMethodBuilder))]</c>.</summary>
    public static AttributeListSyntax PoolingBuilderAttribute() =>
        AttributeOf(
            "global::System.Runtime.CompilerServices.AsyncMethodBuilder",
            AttributeArgument(TypeOf("global::System.Runtime.CompilerServices.PoolingAsyncValueTaskMethodBuilder"))
        );

    /// <summary>
    ///     The node with a documentation comment before it: one <c>///</c> line per entry of <paramref name="lines" />, written as XML
    ///     (<c>&lt;summary&gt;...&lt;/summary&gt;</c>, with <c>&lt;</c> and <c>&gt;</c> escaped in text). The lines are comment trivia, not
    ///     structured documentation trivia, so whitespace normalization indents them and leaves their text alone (it would write
    ///     <c>&lt;see cref = "X"/&gt;</c>); the compiler reads them as documentation when it parses the generated file.
    /// </summary>
    public static TNode Documented<TNode>(this TNode node, params string[] lines)
        where TNode : SyntaxNode
    {
        var trivia = new List<SyntaxTrivia>(lines.Length * 2);
        foreach (var line in lines)
        {
            trivia.Add(Comment("/// " + line));
            trivia.Add(EndOfLine(LineFeed));
        }

        return node.WithLeadingTrivia(TriviaList(trivia).AddRange(node.GetLeadingTrivia()));
    }

    /// <summary><c>#nullable disable warnings</c> or <c>#nullable restore warnings</c>.</summary>
    public static SyntaxTrivia NullableWarnings(bool disable) =>
        Trivia(
            NullableDirectiveTrivia(Token(disable ? SyntaxKind.DisableKeyword : SyntaxKind.RestoreKeyword), true)
               .WithTargetToken(Token(SyntaxKind.WarningsKeyword))
        );

    /// <summary><c>#nullable disable</c> or <c>#nullable enable</c>.</summary>
    public static SyntaxTrivia NullableContext(bool enable) =>
        Trivia(NullableDirectiveTrivia(Token(enable ? SyntaxKind.EnableKeyword : SyntaxKind.DisableKeyword), true));

    /// <summary>
    ///     What <see cref="Render" /> does after <c>NormalizeWhitespace</c>, where the normalized layout is hard to read or wrong:
    ///     <list type="bullet">
    ///         <item>
    ///             members of a type are separated by a blank line, unless both are fields without attributes (normalization puts one only
    ///             after a block);
    ///         </item>
    ///         <item>a constructor with more than one parameter takes one per line;</item>
    ///         <item>a comment in an empty block is indented as the block's content;</item>
    ///         <item>an expression-bodied member breaks after <c>=&gt;</c> and indents its body one level;</item>
    ///         <item>the closing brace of a switch expression goes on its own line (normalization writes <c>... =&gt; throw x};</c>);</item>
    ///         <item><c>is</c> after a closing parenthesis gets its space (normalization writes <c>GetService(typeof(int))is int</c>);</item>
    ///         <item>
    ///             the space normalization leaves after the <c>?</c> of a nullable type is dropped unless a name or keyword follows
    ///             (<c>typeof(int? )</c>, <c>(int? )value</c>, <c>string? []</c>).
    ///         </item>
    ///     </list>
    /// </summary>
    private sealed class Layout : CSharpSyntaxRewriter
    {
        private const string Indentation = "    ";

        public Layout() : base(visitIntoStructuredTrivia: false) { }

        public override SyntaxNode? VisitClassDeclaration(ClassDeclarationSyntax node) => Separate((ClassDeclarationSyntax)base.VisitClassDeclaration(node)!);

        public override SyntaxNode? VisitStructDeclaration(StructDeclarationSyntax node) => Separate((StructDeclarationSyntax)base.VisitStructDeclaration(node)!);

        public override SyntaxNode? VisitRecordDeclaration(RecordDeclarationSyntax node) => Separate((RecordDeclarationSyntax)base.VisitRecordDeclaration(node)!);

        public override SyntaxNode? VisitInterfaceDeclaration(InterfaceDeclarationSyntax node) =>
            Separate((InterfaceDeclarationSyntax)base.VisitInterfaceDeclaration(node)!);

        public override SyntaxNode? VisitArrowExpressionClause(ArrowExpressionClauseSyntax node)
        {
            var visited = (ArrowExpressionClauseSyntax)base.VisitArrowExpressionClause(node)!;
            if (node.Parent is not MemberDeclarationSyntax member)
            {
                return visited;
            }

            // A body that starts with a directive (a nullable island) is already on its own line after it.
            var body = visited.Expression.GetFirstToken();
            if (body.LeadingTrivia.Any(static t => t.IsDirective))
            {
                return visited.WithArrowToken(visited.ArrowToken.WithTrailingTrivia(EndOfLine(LineFeed)))
                              .ReplaceToken(body, body.WithLeadingTrivia(IndentAfterDirectives(body.LeadingTrivia, LineIndentation(member) + Indentation)));
            }

            return visited.WithArrowToken(visited.ArrowToken.WithTrailingTrivia(EndOfLine(LineFeed), Whitespace(LineIndentation(member) + Indentation)));
        }

        public override SyntaxNode? VisitSwitchExpression(SwitchExpressionSyntax node)
        {
            var visited = (SwitchExpressionSyntax)base.VisitSwitchExpression(node)!;
            if (node.CloseBraceToken.GetPreviousToken().TrailingTrivia.Any(static t => t.IsKind(SyntaxKind.EndOfLineTrivia)))
            {
                return visited;
            }

            var indentation = node.OpenBraceToken.LeadingTrivia.Where(static t => t.IsKind(SyntaxKind.WhitespaceTrivia));
            return visited.WithCloseBraceToken(visited.CloseBraceToken.WithLeadingTrivia(TriviaList(EndOfLine(LineFeed)).AddRange(indentation)));
        }

        public override SyntaxNode? VisitBlock(BlockSyntax node)
        {
            var visited = (BlockSyntax)base.VisitBlock(node)!;
            var close = visited.CloseBraceToken;
            if (visited.Statements.Count > 0 || !close.LeadingTrivia.Any(static t => t.IsKind(SyntaxKind.SingleLineCommentTrivia)))
            {
                return visited;
            }

            // A comment in an empty block is indented as its content, not as its closing brace.
            var indentation = visited.OpenBraceToken.LeadingTrivia.Where(static t => t.IsKind(SyntaxKind.WhitespaceTrivia)).Select(static t => t.ToString()).LastOrDefault() ?? "";
            var leading = new List<SyntaxTrivia>();
            foreach (var trivia in close.LeadingTrivia)
            {
                if (trivia.IsKind(SyntaxKind.SingleLineCommentTrivia))
                {
                    leading.AddRange([Whitespace(indentation + Indentation), trivia, EndOfLine(LineFeed)]);
                }
            }

            leading.Add(Whitespace(indentation));
            return visited.WithCloseBraceToken(close.WithLeadingTrivia(leading));
        }

        public override SyntaxNode? VisitParameterList(ParameterListSyntax node)
        {
            var visited = (ParameterListSyntax)base.VisitParameterList(node)!;
            if (node.Parent is not ConstructorDeclarationSyntax constructor || visited.Parameters.Count < 2)
            {
                return visited;
            }

            var indentation = LineIndentation(constructor) + Indentation;
            var parameters = visited.Parameters.Select(p => p.WithLeadingTrivia(EndOfLine(LineFeed), Whitespace(indentation)));
            return visited.WithParameters(SeparatedList(parameters, Enumerable.Repeat(Token(SyntaxKind.CommaToken), visited.Parameters.Count - 1)));
        }

        public override SyntaxNode? VisitIsPatternExpression(IsPatternExpressionSyntax node)
        {
            var visited = (IsPatternExpressionSyntax)base.VisitIsPatternExpression(node)!;
            var before = visited.Expression.GetLastToken();
            return before.TrailingTrivia.Count > 0 || visited.IsKeyword.LeadingTrivia.Count > 0
                ? visited
                : visited.ReplaceToken(before, before.WithTrailingTrivia(Space));
        }

        public override SyntaxNode? VisitNullableType(NullableTypeSyntax node)
        {
            var visited = (NullableTypeSyntax)base.VisitNullableType(node)!;
            // Only a name after the type (a parameter, field or local) keeps the space: `string? value`, but `string?[]`, `int?)`.
            var next = node.QuestionToken.GetNextToken();
            return next.IsKind(SyntaxKind.IdentifierToken) || SyntaxFacts.IsKeywordKind(next.Kind())
                ? visited
                : visited.WithQuestionToken(visited.QuestionToken.WithTrailingTrivia());
        }

        /// <summary>The indentation of the line a member's declaration (its modifiers or type, after attributes) starts on.</summary>
        private static string LineIndentation(MemberDeclarationSyntax member)
        {
            var first = member.Modifiers.Count > 0 ? member.Modifiers[0] : member.ChildNodes().FirstOrDefault(static n => n is not AttributeListSyntax)?.GetFirstToken() ?? member.GetFirstToken();
            var leading = first.LeadingTrivia;
            return leading.Count > 0 && leading[^1].IsKind(SyntaxKind.WhitespaceTrivia) ? leading[^1].ToString() : "";
        }

        /// <summary>The trivia with the whitespace after its last directive replaced by <paramref name="indentation" />.</summary>
        private static SyntaxTriviaList IndentAfterDirectives(SyntaxTriviaList trivia, string indentation)
        {
            var last = -1;
            for (var i = 0; i < trivia.Count; i++)
            {
                if (trivia[i].IsDirective)
                {
                    last = i;
                }
            }

            var kept = new List<SyntaxTrivia>(last + 2);
            for (var i = 0; i <= last; i++)
            {
                kept.Add(trivia[i]);
            }

            kept.Add(Whitespace(indentation));
            return TriviaList(kept);
        }

        private static int LineBreaks(SyntaxTriviaList trivia)
        {
            var count = 0;
            foreach (var item in trivia)
            {
                if (item.IsKind(SyntaxKind.EndOfLineTrivia))
                {
                    count++;
                }
            }

            return count;
        }

        /// <summary>The line breaks before the first trivia that is neither a line break nor whitespace.</summary>
        private static int LeadingLineBreaks(SyntaxTriviaList trivia)
        {
            var count = 0;
            foreach (var item in trivia)
            {
                if (item.IsKind(SyntaxKind.EndOfLineTrivia))
                {
                    count++;
                }
                else if (!item.IsKind(SyntaxKind.WhitespaceTrivia))
                {
                    break;
                }
            }

            return count;
        }

        private static TNode Separate<TNode>(TNode type)
            where TNode : TypeDeclarationSyntax
        {
            var members = type.Members;
            var separated = new List<SyntaxToken>();
            for (var i = 1; i < members.Count; i++)
            {
                if (members[i - 1] is FieldDeclarationSyntax { AttributeLists.Count: 0 } && members[i] is FieldDeclarationSyntax { AttributeLists.Count: 0 })
                {
                    continue;
                }

                var first = members[i].GetFirstToken();
                if (LineBreaks(first.GetPreviousToken().TrailingTrivia) + LeadingLineBreaks(first.LeadingTrivia) < 2)
                {
                    separated.Add(first);
                }
            }

            return separated.Count == 0
                ? type
                : type.ReplaceTokens(separated, static (_, token) => token.WithLeadingTrivia(token.LeadingTrivia.Insert(0, EndOfLine(LineFeed))));
        }
    }
}
