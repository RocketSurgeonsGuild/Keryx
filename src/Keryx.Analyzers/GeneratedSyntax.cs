    public static LocalDeclarationStatementSyntax Var(string name, ExpressionSyntax value) => Local(VarType(), name, value);

    public static LocalDeclarationStatementSyntax Local(TypeSyntax type, string name, ExpressionSyntax? value = null) =>
        LocalDeclarationStatement(VariableDeclaration(type, SingletonSeparatedList(Declarator(name, value))));

    public static FieldDeclarationSyntax Field(SyntaxTokenList modifiers, TypeSyntax type, string name, ExpressionSyntax? initializer = null) =>
        FieldDeclaration(VariableDeclaration(type, SingletonSeparatedList(Declarator(name, initializer)))).WithModifiers(modifiers);

    public static MethodDeclarationSyntax Method(SyntaxTokenList modifiers, TypeSyntax returnType, string name, ParameterListSyntax parameters) =>
        MethodDeclaration(returnType, Identifier(Spaced, name, default)).WithModifiers(modifiers).WithParameterList(parameters);

    /// <summary>
    ///     The method with an expression body: <c>=&gt;</c> ends the line of the declaration, at <paramref name="depth" />, and the body is on
    ///     the next line, one level deeper.
    /// </summary>
    public static MethodDeclarationSyntax Expression(this MethodDeclarationSyntax method, int depth, ExpressionSyntax body) =>
        method
           .WithExpressionBody(ArrowExpressionClause(Token(Spaced, SyntaxKind.EqualsGreaterThanToken, Line(depth + 1)), body))
           .WithSemicolonToken(Semicolon);

    /// <summary>
    ///     The method with an expression body written with nullable warnings disabled (OQ-58): after <c>=&gt;</c>, a blank line,
    ///     <c>#nullable disable warnings</c> and the body at <paramref name="depth" />, the depth of the declaration. That is the layout the
    ///     generator has always written for this body (step 5's normalization and fix-up pass); it is kept so the output does not change.
    ///     The type that holds the method restores the warnings before its closing brace (<see cref="WithBody{TType}" />).
    /// </summary>
    public static MethodDeclarationSyntax NullableObliviousExpression(this MethodDeclarationSyntax method, int depth, ExpressionSyntax body) =>
        method
           .WithExpressionBody(
                ArrowExpressionClause(
                    Token(Spaced, SyntaxKind.EqualsGreaterThanToken, TriviaList(NewLine)),
                    WithFirstTokenLeading(body, TriviaList(NewLine, NullableWarningsDisable, Indent(depth)))
                )
            )
           .WithSemicolonToken(Semicolon);

    /// <summary>The method with a block body: its braces at <paramref name="depth" />, the depth of the declaration (<see cref="Body" />).</summary>
    public static MethodDeclarationSyntax Statements(this MethodDeclarationSyntax method, int depth, IEnumerable<StatementSyntax> statements) =>
        method.WithBody(Body(depth, statements));

    /// <summary>The method with a type parameter constraint, <c>where parameter : constraint</c>, on its own line one level deeper.</summary>
    public static MethodDeclarationSyntax Where(this MethodDeclarationSyntax method, int depth, string parameter, TypeSyntax constraint) =>
        method.WithConstraintClauses(
            SingletonList(
                TypeParameterConstraintClause(
                    Token(Line(depth + 1), SyntaxKind.WhereKeyword, Spaced),
                    IdentifierName(parameter),
                    Operator(SyntaxKind.ColonToken),
                    SingletonSeparatedList<TypeParameterConstraintSyntax>(TypeConstraint(constraint))
                )
            )
        );

    /// <summary>
    ///     A constructor at <paramref name="depth" />: its parameters one per line when it has more than one (<see cref="ParamsPerLine" />),
    ///     its body a block (<see cref="Body" />).
    /// </summary>
    public static ConstructorDeclarationSyntax Constructor(
        int depth,
        SyntaxTokenList modifiers,
        string name,
        ParameterSyntax[] parameters,
        IEnumerable<StatementSyntax> statements
    ) =>
        ConstructorDeclaration(Identifier(name))
           .WithModifiers(modifiers)
           .WithParameterList(ParamsPerLine(depth, parameters))
           .WithBody(Body(depth, statements));

    /// <summary>
    ///     A block: its braces on their own lines at <paramref name="depth" />, each statement on the next line one level deeper (laid out by
    ///     <paramref name="statements" />' own depth for the lines after its first), with a blank line after a statement that ends with a
    ///     block (an <c>if</c>, <c>try</c>, <c>foreach</c> or <c>switch</c>) when another follows.
    /// </summary>
    /// <param name="depth">The depth of the braces.</param>
    /// <param name="statements">The statements, built for <paramref name="depth" /> + 1.</param>
    /// <param name="nullableIsland">
    ///     Whether the last statement is written with nullable warnings disabled (OQ-58): <c>#nullable disable warnings</c> before it and
    ///     <c>#nullable restore warnings</c> before the closing brace.
    /// </param>
    /// <param name="comment">A comment for an empty block, on its own line inside it.</param>
    public static BlockSyntax Body(int depth, IEnumerable<StatementSyntax> statements, bool nullableIsland = false, string? comment = null)
    {
        var lines = new List<StatementSyntax>();
        foreach (var statement in statements)
        {
            lines.Add(statement);
        }

        for (var i = 0; i < lines.Count; i++)
        {
            var blank = i > 0 && EndsWithBlock(lines[i - 1]);
            var leading = nullableIsland && i == lines.Count - 1
                ? blank ? TriviaList(NewLine, NewLine, NullableWarningsDisable, Indent(depth + 1)) : TriviaList(NewLine, NullableWarningsDisable, Indent(depth + 1))
                : LineStart(default, depth + 1, blank, first: false);
            lines[i] = WithLineStart(lines[i], leading);
        }

        var close = nullableIsland ? TriviaList(NewLine, NullableWarningsRestore, Indent(depth))
            : comment is not null ? TriviaList(NewLine, Indent(depth + 1), Comment(comment), NewLine, Indent(depth))
            : Line(depth);
        return Block(default, OpenBrace(depth), List(lines), Token(close, SyntaxKind.CloseBraceToken, default));
    }

    /// <summary><c>if (condition) { statements }</c> at <paramref name="depth" />, with an optional <c>else if</c> built for the same depth.</summary>
    public static IfStatementSyntax If(int depth, ExpressionSyntax condition, IEnumerable<StatementSyntax> statements, IfStatementSyntax? elseIf = null) =>
        IfStatement(
            default,
            Keyword(SyntaxKind.IfKeyword),
            Token(SyntaxKind.OpenParenToken),
            condition,
            Token(SyntaxKind.CloseParenToken),
            Body(depth, statements),
            elseIf is null ? null : ElseClause(Token(Line(depth), SyntaxKind.ElseKeyword, Spaced), elseIf)
        );

    /// <summary><c>try { statements }</c> and its catch clauses (<see cref="Catch" />), at <paramref name="depth" />.</summary>
    public static TryStatementSyntax Try(int depth, IEnumerable<StatementSyntax> statements, params CatchClauseSyntax[] catches) =>
        TryStatement(default, Token(SyntaxKind.TryKeyword), Body(depth, statements), List(catches), null);

    /// <summary><c>catch (type name) { statements }</c> on its own line at <paramref name="depth" />, or <c>catch (type)</c> without a name.</summary>
    public static CatchClauseSyntax Catch(int depth, TypeSyntax type, string? name, IEnumerable<StatementSyntax> statements, string? comment = null) =>
        CatchClause(
            Token(Line(depth), SyntaxKind.CatchKeyword, Spaced),
            CatchDeclaration(Token(SyntaxKind.OpenParenToken), type, name is null ? default : Identifier(Spaced, name, default), Token(SyntaxKind.CloseParenToken)),
            null,
            Body(depth, statements, comment: comment)
        );

    /// <summary><c>foreach (var name in collection) { statements }</c> at <paramref name="depth" />.</summary>
    public static ForEachStatementSyntax ForEach(int depth, string name, ExpressionSyntax collection, IEnumerable<StatementSyntax> statements) =>
        ForEachStatement(
            default,
            default,
            Keyword(SyntaxKind.ForEachKeyword),
            Token(SyntaxKind.OpenParenToken),
            IdentifierName("var"),
            Identifier(Spaced, name, default),
            Operator(SyntaxKind.InKeyword),
            collection,
            Token(SyntaxKind.CloseParenToken),
            Body(depth, statements)
        );

    /// <summary>
    ///     <c>switch (governing) { sections }</c> at <paramref name="depth" />: each label on its own line one level deeper, each statement of
    ///     a section on its own line two levels deeper.
    /// </summary>
    public static SwitchStatementSyntax Switch(int depth, ExpressionSyntax governing, IEnumerable<SwitchSectionSyntax> sections)
    {
        var label = Line(depth + 1);
        var line = Line(depth + 2);
        var laidOut = new List<SwitchSectionSyntax>();
        foreach (var section in sections)
        {
            var labels = new SwitchLabelSyntax[section.Labels.Count];
            for (var i = 0; i < labels.Length; i++)
            {
                labels[i] = section.Labels[i].WithKeyword(section.Labels[i].Keyword.WithLeadingTrivia(label));
            }

            var statements = new StatementSyntax[section.Statements.Count];
            for (var i = 0; i < statements.Length; i++)
            {
                statements[i] = WithLineStart(section.Statements[i], line);
            }

            laidOut.Add(section.WithLabels(List(labels)).WithStatements(List(statements)));
        }

        return SwitchStatement(
            default,
            Keyword(SyntaxKind.SwitchKeyword),
            Token(SyntaxKind.OpenParenToken),
            governing,
            Token(SyntaxKind.CloseParenToken),
            OpenBrace(depth),
            List(laidOut),
            Token(Line(depth), SyntaxKind.CloseBraceToken, default)
        );
    }

    /// <summary>A switch section <c>case var _ when guard: statement</c>: the guard alone selects it.</summary>
    public static SwitchSectionSyntax WhenSection(ExpressionSyntax guard, StatementSyntax statement) =>
        Section(
            CasePatternSwitchLabel(
                Keyword(SyntaxKind.CaseKeyword),
                VarPattern(Keyword(SyntaxKind.VarKeyword), DiscardDesignation()),
                WhenClause(Operator(SyntaxKind.WhenKeyword), guard),
                Token(SyntaxKind.ColonToken)
            ),
            statement
        );

    /// <summary>
    ///     A switch section with a type pattern: <c>case type designation: statement</c>, or <c>case type: statement</c> without a designation.
    /// </summary>
    public static SwitchSectionSyntax TypeSection(string type, string? designation, StatementSyntax statement) =>
        Section(
            CasePatternSwitchLabel(
                Keyword(SyntaxKind.CaseKeyword),
                designation is null ? TypePattern(TypeName(type)) : DeclarationPattern(TypeName(type), Designation(designation)),
                null,
                Token(SyntaxKind.ColonToken)
            ),
            statement
        );

    /// <summary>The switch section <c>default: statement</c>.</summary>
    public static SwitchSectionSyntax DefaultSection(StatementSyntax statement) => Section(DefaultSwitchLabel(), statement);

    /// <summary>A switch section <c>case constant: statement</c>.</summary>
    public static SwitchSectionSyntax ConstantSection(int constant, StatementSyntax statement) =>
        Section(CaseSwitchLabel(Keyword(SyntaxKind.CaseKeyword), Number(constant), Token(SyntaxKind.ColonToken)), statement);

    /// <summary><c>modifiers class name : baseType</c>, without members (<see cref="WithBody{TType}" />).</summary>
    public static ClassDeclarationSyntax Class(SyntaxTokenList modifiers, string name, string? baseType = null)
    {
        var declaration = ClassDeclaration(Identifier(name)).WithModifiers(modifiers).WithKeyword(Keyword(SyntaxKind.ClassKeyword));
        return baseType is null ? declaration : declaration.WithBaseList(Base(baseType));
    }

    /// <summary><c>modifiers struct name(parameters) : baseType</c>, without members (<see cref="WithBody{TType}" />).</summary>
    public static StructDeclarationSyntax Struct(SyntaxTokenList modifiers, string name, ParameterListSyntax? parameters, string baseType) =>
        StructDeclaration(Identifier(name))
           .WithModifiers(modifiers)
           .WithKeyword(Keyword(SyntaxKind.StructKeyword))
           .WithParameterList(parameters)
           .WithBaseList(Base(baseType));

    /// <summary>
    ///     The type with its braces on their own lines at <paramref name="depth" />, the depth of its declaration, and its members one level
    ///     deeper, a blank line between two members unless both are fields without attributes.
    /// </summary>
    /// <param name="type">The type declaration, without members.</param>
    /// <param name="depth">The depth of its declaration.</param>
    /// <param name="members">The members, built for <paramref name="depth" /> + 1.</param>
    /// <param name="restoreNullableWarnings">
    ///     Whether <c>#nullable restore warnings</c> goes before the closing brace, after a member written with nullable warnings disabled
    ///     (<see cref="NullableObliviousExpression" />).
    /// </param>
    public static TType WithBody<TType>(this TType type, int depth, IEnumerable<MemberDeclarationSyntax> members, bool restoreNullableWarnings = false)
        where TType : TypeDeclarationSyntax =>
        (TType)type
              .WithOpenBraceToken(OpenBrace(depth))
              .WithMembers(Lines(depth + 1, members))
              .WithCloseBraceToken(
                   Token(
                       restoreNullableWarnings ? TriviaList(NewLine, NullableWarningsRestore, Indent(depth)) : Line(depth),
                       SyntaxKind.CloseBraceToken,
                       default
                   )
               );

    /// <summary>One attribute in its own list: <c>[name(arguments)]</c>.</summary>
    public static AttributeListSyntax AttributeOf(string name, params AttributeArgumentSyntax[] arguments)
    {
        var attribute = Attribute(Qualified(name));
        return AttributeList(SingletonSeparatedList(arguments.Length == 0 ? attribute : attribute.WithArgumentList(AttributeArgumentList(Commas(arguments)))));
    }

    /// <summary>A named attribute argument, <c>name = value</c>.</summary>
    public static AttributeArgumentSyntax Named(string name, ExpressionSyntax value) =>
        AttributeArgument(NameEquals(IdentifierName(name), Operator(SyntaxKind.EqualsToken)), null, value);

    /// <summary><c>[GeneratedCode("Keryx", version)]</c>, written on generated members and on the types Keryx owns.</summary>
    public static AttributeListSyntax GeneratedCodeAttribute() => GeneratedCode;

    /// <summary><c>[MethodImpl(MethodImplOptions.NoInlining)]</c>.</summary>
    public static AttributeListSyntax NoInliningAttribute() => NoInlining;

    /// <summary><c>[AsyncMethodBuilder(typeof(PoolingAsyncValueTaskMethodBuilder))]</c>.</summary>
    public static AttributeListSyntax PoolingBuilderAttribute() => PoolingBuilder;

    /// <summary>
    ///     The member with a documentation comment before it: one <c>///</c> line per entry of <paramref name="lines" />, written as XML
    ///     (<c>&lt;summary&gt;...&lt;/summary&gt;</c>, with <c>&lt;</c> and <c>&gt;</c> escaped in text). The lines are comment trivia, not
    ///     structured documentation trivia, so they are written exactly as given; the compiler reads them as documentation when it parses the
    ///     generated file. The type body that holds the member indents each line (<see cref="WithBody{TType}" />).
    /// </summary>
    public static TNode Documented<TNode>(this TNode node, params string[] lines)
        where TNode : MemberDeclarationSyntax
    {
        var trivia = new List<SyntaxTrivia>(lines.Length * 2);
        foreach (var line in lines)
        {
            trivia.Add(Comment("/// " + line));
            trivia.Add(NewLine);
        }

        return (TNode)WithHeadLeading(node, TriviaList(trivia).AddRange(HeadToken(node).LeadingTrivia));
    }

    /// <summary>
    ///     The type with an attribute written with the nullable context disabled: <c>#nullable disable</c> before its attribute lists and
    ///     <c>#nullable enable</c> after them (not <c>restore</c>, which returns to the project default, disabled for generated code).
    /// </summary>
    public static TType WithNullableObliviousAttributes<TType>(this TType type)
        where TType : MemberDeclarationSyntax
    {
        var lists = type.AttributeLists;
        var first = lists[0].OpenBracketToken;
        var modifier = type.Modifiers[0];
        return (TType)type
                     .WithAttributeLists(lists.Replace(lists[0], lists[0].WithOpenBracketToken(first.WithLeadingTrivia(first.LeadingTrivia.Insert(0, NullableDisable)))))
                     .WithModifiers(type.Modifiers.Replace(modifier, modifier.WithLeadingTrivia(modifier.LeadingTrivia.Insert(0, NullableEnable))));
    }

    /// <summary>A line feed and <paramref name="depth" /> levels of indentation: the start of a line.</summary>
    private static SyntaxTriviaList Line(int depth) => depth < LineStarts.Length ? LineStarts[depth] : TriviaList(NewLine, Indent(depth));

    /// <summary>The whitespace of <paramref name="depth" /> levels of indentation.</summary>
    private static SyntaxTrivia Indent(int depth) => depth < Indents.Length ? Indents[depth] : Whitespace(string.Concat(Enumerable.Repeat(Indentation, depth)));

    /// <summary>A keyword followed by a space.</summary>
    private static SyntaxToken Keyword(SyntaxKind kind) => Token(default, kind, Spaced);

    /// <summary>An operator with a space on each side.</summary>
    private static SyntaxToken Operator(SyntaxKind kind) => Token(Spaced, kind, Spaced);

    /// <summary><c>{</c> on its own line at <paramref name="depth" />.</summary>
    private static SyntaxToken OpenBrace(int depth) => Token(Line(depth), SyntaxKind.OpenBraceToken, default);

    private static IdentifierNameSyntax VarType() => IdentifierName("var");

    private static SingleVariableDesignationSyntax Designation(string name) => SingleVariableDesignation(Identifier(Spaced, name, default));

    private static VariableDeclaratorSyntax Declarator(string name, ExpressionSyntax? value)
    {
        var declarator = VariableDeclarator(Identifier(Spaced, name, default));
        return value is null ? declarator : declarator.WithInitializer(EqualsValueClause(Operator(SyntaxKind.EqualsToken), value));
    }

    private static BinaryExpressionSyntax Binary(SyntaxKind kind, SyntaxKind operatorKind, ExpressionSyntax left, ExpressionSyntax right) =>
        BinaryExpression(kind, left, Operator(operatorKind), right);

    private static BaseListSyntax Base(string type) => BaseList(Operator(SyntaxKind.ColonToken), SingletonSeparatedList<BaseTypeSyntax>(SimpleBaseType(TypeName(type))));

    private static SwitchSectionSyntax Section(SwitchLabelSyntax label, StatementSyntax statement) => SwitchSection(SingletonList(label), SingletonList(statement));

    /// <summary>The nodes separated by <c>, </c>.</summary>
    private static SeparatedSyntaxList<TNode> Commas<TNode>(IEnumerable<TNode> nodes)
        where TNode : SyntaxNode
    {
        var items = new List<SyntaxNodeOrToken>();
        foreach (var node in nodes)
        {
            if (items.Count > 0)
            {
                items.Add(Comma);
            }

            items.Add(node);
        }

        return SeparatedList<TNode>(items);
    }

    /// <summary>A preprocessor directive as trivia, with its line feed.</summary>
    private static SyntaxTrivia Directive(string text) => ParseLeadingTrivia(text + LineFeed).Single(static t => t.IsDirective);

    /// <summary>
    ///     The members laid out at <paramref name="depth" />: each on its own line, a blank line before each one after the first unless it and
    ///     the one before are both fields without attributes.
    /// </summary>
    private static SyntaxList<MemberDeclarationSyntax> Lines(int depth, IEnumerable<MemberDeclarationSyntax> members)
    {
        var lines = new List<MemberDeclarationSyntax>();
        MemberDeclarationSyntax? previous = null;
        foreach (var member in members)
        {
            var blank = previous is not null && !( IsPlainField(previous) && IsPlainField(member) );
            lines.Add(Place(member, depth, LineStart(HeadToken(member).LeadingTrivia, depth, blank, first: false)));
            previous = member;
        }

        return List(lines);
    }

    private static bool IsPlainField(MemberDeclarationSyntax member) => member is FieldDeclarationSyntax { AttributeLists.Count: 0 };

    /// <summary>
    ///     The member with the lines of its head laid out at <paramref name="depth" />: <paramref name="leading" /> before its first token, and
    ///     each further attribute list and the declaration after its attribute lists on a line of their own.
    /// </summary>
    private static MemberDeclarationSyntax Place(MemberDeclarationSyntax member, int depth, SyntaxTriviaList leading)
    {
        var lists = member.AttributeLists;
        if (lists.Count == 0)
        {
            return WithHeadLeading(member, leading);
        }

        var placed = new AttributeListSyntax[lists.Count];
        for (var i = 0; i < lists.Count; i++)
        {
            var open = lists[i].OpenBracketToken;
            placed[i] = lists[i].WithOpenBracketToken(open.WithLeadingTrivia(i == 0 ? leading : LineStart(open.LeadingTrivia, depth, blank: false, first: false)));
        }

        member = member.WithAttributeLists(List(placed));
        var modifiers = member.Modifiers;
        if (modifiers.Count > 0)
        {
            return member.WithModifiers(modifiers.Replace(modifiers[0], modifiers[0].WithLeadingTrivia(LineStart(modifiers[0].LeadingTrivia, depth, blank: false, first: false))));
        }

        var next = member.AttributeLists[^1].CloseBracketToken.GetNextToken();
        return member.ReplaceToken(next, next.WithLeadingTrivia(LineStart(next.LeadingTrivia, depth, blank: false, first: false)));
    }

    /// <summary>
    ///     The leading trivia of the first token of a line at <paramref name="depth" />: the line feed that ends the line before (none at the
    ///     start of the file), a second one for a blank line, the trivia already there with each comment line indented and directives at
    ///     column 0, and the indentation.
    /// </summary>
    private static SyntaxTriviaList LineStart(SyntaxTriviaList existing, int depth, bool blank, bool first)
    {
        if (existing.Count == 0 && !first && depth > 0 && depth < LineStarts.Length)
        {
            return blank ? BlankLineStarts[depth] : LineStarts[depth];
        }

        var trivia = new List<SyntaxTrivia>(existing.Count * 2 + 3);
        if (!first)
        {
            trivia.Add(NewLine);
        }

        if (blank)
        {
            trivia.Add(NewLine);
        }

        foreach (var item in existing)
        {
            if (depth > 0 && item.IsKind(SyntaxKind.SingleLineCommentTrivia))
            {
                trivia.Add(Indent(depth));
            }

            trivia.Add(item);
        }

        if (depth > 0)
        {
            trivia.Add(Indent(depth));
        }

        return TriviaList(trivia);
    }

    /// <summary>The first token of a member's head: its first attribute list's <c>[</c>, else its first modifier, else its first token.</summary>
    private static SyntaxToken HeadToken(MemberDeclarationSyntax member) =>
        member.AttributeLists.Count > 0 ? member.AttributeLists[0].OpenBracketToken
        : member.Modifiers.Count > 0 ? member.Modifiers[0]
        : member.GetFirstToken();

    /// <summary>The member with <paramref name="leading" /> as the leading trivia of its first token (<see cref="HeadToken" />).</summary>
    private static MemberDeclarationSyntax WithHeadLeading(MemberDeclarationSyntax member, SyntaxTriviaList leading)
    {
        if (member.AttributeLists.Count > 0)
        {
            var lists = member.AttributeLists;
            return member.WithAttributeLists(lists.Replace(lists[0], lists[0].WithOpenBracketToken(lists[0].OpenBracketToken.WithLeadingTrivia(leading))));
        }

        return member.Modifiers.Count > 0
            ? member.WithModifiers(member.Modifiers.Replace(member.Modifiers[0], member.Modifiers[0].WithLeadingTrivia(leading)))
            : member.WithLeadingTrivia(leading);
    }

    private static bool EndsWithBlock(StatementSyntax statement) =>
        statement is IfStatementSyntax or TryStatementSyntax or ForEachStatementSyntax or SwitchStatementSyntax or BlockSyntax;

    /// <summary>
    ///     The statement with <paramref name="leading" /> before its first token. The statements the helpers build start with a keyword or
    ///     <c>var</c>, which is replaced directly; anything else goes through the first token.
    /// </summary>
    private static StatementSyntax WithLineStart(StatementSyntax statement, SyntaxTriviaList leading) =>
        statement switch
        {
            ReturnStatementSyntax s => s.WithReturnKeyword(s.ReturnKeyword.WithLeadingTrivia(leading)),
            ThrowStatementSyntax s => s.WithThrowKeyword(s.ThrowKeyword.WithLeadingTrivia(leading)),
            IfStatementSyntax s => s.WithIfKeyword(s.IfKeyword.WithLeadingTrivia(leading)),
            TryStatementSyntax s => s.WithTryKeyword(s.TryKeyword.WithLeadingTrivia(leading)),
            ForEachStatementSyntax s => s.WithForEachKeyword(s.ForEachKeyword.WithLeadingTrivia(leading)),
            SwitchStatementSyntax s => s.WithSwitchKeyword(s.SwitchKeyword.WithLeadingTrivia(leading)),
            LocalDeclarationStatementSyntax { Declaration.Type: IdentifierNameSyntax type } s =>
                s.WithDeclaration(s.Declaration.WithType(type.WithIdentifier(type.Identifier.WithLeadingTrivia(leading)))),
            ExpressionStatementSyntax s => s.WithExpression(WithFirstTokenLeading(s.Expression, leading)),
            _ => WithFirstTokenLeading(statement, leading),
        };

    /// <summary>
    ///     The expression with <paramref name="leading" /> before its first token, replaced down its left edge with the typed <c>With</c>
    ///     methods of the expressions the helpers build (no rewrite of the tree); anything else goes through the first token.
    /// </summary>
    private static ExpressionSyntax WithFirstTokenLeading(ExpressionSyntax expression, SyntaxTriviaList leading) =>
        expression switch
        {
            IdentifierNameSyntax e => e.WithIdentifier(e.Identifier.WithLeadingTrivia(leading)),
            GenericNameSyntax e => e.WithIdentifier(e.Identifier.WithLeadingTrivia(leading)),
            AliasQualifiedNameSyntax e => e.WithAlias(e.Alias.WithIdentifier(e.Alias.Identifier.WithLeadingTrivia(leading))),
            QualifiedNameSyntax e => e.WithLeft((NameSyntax)WithFirstTokenLeading(e.Left, leading)),
            MemberAccessExpressionSyntax e => e.WithExpression(WithFirstTokenLeading(e.Expression, leading)),
            InvocationExpressionSyntax e => e.WithExpression(WithFirstTokenLeading(e.Expression, leading)),
            AssignmentExpressionSyntax e => e.WithLeft(WithFirstTokenLeading(e.Left, leading)),
            ParenthesizedExpressionSyntax e => e.WithOpenParenToken(e.OpenParenToken.WithLeadingTrivia(leading)),
            AwaitExpressionSyntax e => e.WithAwaitKeyword(e.AwaitKeyword.WithLeadingTrivia(leading)),
            ObjectCreationExpressionSyntax e => e.WithNewKeyword(e.NewKeyword.WithLeadingTrivia(leading)),
            _ => WithFirstTokenLeading<ExpressionSyntax>(expression, leading),
        };

    private static TNode WithFirstTokenLeading<TNode>(TNode node, SyntaxTriviaList leading)
        where TNode : SyntaxNode
    {
        var first = node.GetFirstToken();
        return node.ReplaceToken(first, first.WithLeadingTrivia(leading));
    }
