    public static ImplicitObjectCreationExpressionSyntax TargetTypedNew(params ExpressionSyntax[] arguments) =>
        ImplicitObjectCreationExpression(Token(SyntaxKind.NewKeyword), ArgumentList(Commas(arguments.Select(Argument))), null);

    public static ObjectCreationExpressionSyntax New(TypeSyntax type, params ExpressionSyntax[] arguments) =>
        ObjectCreationExpression(Keyword(SyntaxKind.NewKeyword), type, ArgumentList(Commas(arguments.Select(Argument))), null);

