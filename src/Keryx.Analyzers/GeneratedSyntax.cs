using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace Keryx.Analyzers;

/// <summary>
///     What the emitters share to build generated sources with Roslyn's <see cref="SyntaxFactory" />, the way Dovetail's generators do: names
///     and types from the models' fully qualified (<c>global::</c>) strings, the attributes and documentation comments Keryx writes, and
///     <see cref="Render" />. Syntax is built only inside <c>RegisterSourceOutput</c>: incremental models carry strings, never syntax.
/// </summary>
/// <remarks>
///     The syntax is built with its whitespace (OQ-66): nothing normalizes it afterwards. Within a line, the helpers create each token with
///     the space it needs (<c>public </c>, <c> = </c>, <c>, </c>, <c>return </c>). Lines are laid out by the containers, from the depth they
///     are given (four spaces per level, <c>\n</c> line endings on every platform, so the output is deterministic): a construct never writes
///     the line break and indentation before its own first line, the container that holds it does (a type body for its members, a block for
///     its statements, a switch for its labels and statements), as leading trivia of the first token of the line. A construct that spans
///     lines (a block, an <c>if</c>, a type) is given the depth of its first line and lays out the lines after it. The rules are the layout
///     whitespace normalization gave before: a blank line between the members of a type unless both are fields without attributes, a blank
///     line after a statement that ends with a block unless the block closes, a break after <c>=&gt;</c> with the body one level deeper, a
///     constructor's parameters one per line when it has more than one, and a documentation comment line by line at its member's depth.
/// </remarks>
internal static class GeneratedSyntax
{
    /// <summary>
    ///     Generated code names the user's request, response, service and handler types only because the user declared a handler for them,
    ///     so a deprecated (<c>[Obsolete]</c>) one must not turn into CS0612/CS0618 in a generated file, which the user cannot suppress at
    ///     their own source.
    /// </summary>
    public const string ObsoletePragma = "#pragma warning disable CS0612, CS0618";

    private const string LineFeed = "\n";
    private const string Indentation = "    ";
    private const string Header = "// <auto-generated/>" + LineFeed + "#nullable enable" + LineFeed;

    private static readonly SyntaxTrivia NewLine = EndOfLine(LineFeed);
    private static readonly SyntaxTriviaList Spaced = TriviaList(Space);
    private static readonly SyntaxToken Comma = Token(default, SyntaxKind.CommaToken, Spaced);
    private static readonly SyntaxToken Semicolon = Token(SyntaxKind.SemicolonToken);
    private static readonly SyntaxTrivia[] Indents = [.. Enumerable.Range(0, 12).Select(static depth => Whitespace(string.Concat(Enumerable.Repeat(Indentation, depth))))];

    /// <summary>The start of a line at each depth: a line feed and the indentation.</summary>
    private static readonly SyntaxTriviaList[] LineStarts = [.. Enumerable.Range(0, 12).Select(static depth => TriviaList(NewLine, Indents[depth]))];

    /// <summary>The start of a line after a blank line at each depth.</summary>
    private static readonly SyntaxTriviaList[] BlankLineStarts = [.. Enumerable.Range(0, 12).Select(static depth => TriviaList(NewLine, NewLine, Indents[depth]))];

    /// <summary>The version in <c>[GeneratedCode("Keryx", version)]</c>.</summary>
    public static string Version { get; } = typeof(GeneratedSyntax).Assembly.GetName().Version?.ToString() ?? "1.0.0";

    // The attribute lists every file writes the same way are built once: syntax is immutable, so one node can go into any number of trees.
    private static readonly AttributeListSyntax GeneratedCode = AttributeOf(
        "global::System.CodeDom.Compiler.GeneratedCode",
        AttributeArgument(StringLiteral("Keryx")),
        AttributeArgument(StringLiteral(Version))
    );

    private static readonly AttributeListSyntax NoInlining = AttributeOf(
        "global::System.Runtime.CompilerServices.MethodImpl",
        AttributeArgument(ParseName("global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining"))
    );

    private static readonly AttributeListSyntax PoolingBuilder = AttributeOf(
        "global::System.Runtime.CompilerServices.AsyncMethodBuilder",
        AttributeArgument(TypeOfExpression(ParseTypeName("global::System.Runtime.CompilerServices.PoolingAsyncValueTaskMethodBuilder")))
    );

    private static readonly SyntaxTrivia NullableWarningsDisable = Directive("#nullable disable warnings");
    private static readonly SyntaxTrivia NullableWarningsRestore = Directive("#nullable restore warnings");
    private static readonly SyntaxTrivia NullableDisable = Directive("#nullable disable");
    private static readonly SyntaxTrivia NullableEnable = Directive("#nullable enable");

    /// <summary>
    ///     The types and names parsed while one file is built (<see cref="TypeName" />, <see cref="Qualified" />), by their text: the emitters
    ///     name the same few dozen types thousands of times in a large host, and a parsed node can appear in a tree any number of times (a
    ///     factory takes its immutable green node). Parsing each type name every time it is written was a third of the time
    ///     the host generator spent building the tree (OQ-66). Per thread, because generators may run in parallel, and emptied by
    ///     <see cref="Render" /> when the file is done (or by the next file's, if building one was cancelled), so nothing outlives a file.
    /// </summary>
    [ThreadStatic]
    private static Dictionary<string, TypeSyntax>? _types;

    /// <inheritdoc cref="_types" />
    [ThreadStatic]
    private static Dictionary<string, NameSyntax>? _names;

    /// <summary>
    ///     The source text of a generated file: the header (<c>// &lt;auto-generated/&gt;</c>, <c>#nullable enable</c> and, unless it is
    ///     <see langword="null" />, <paramref name="pragma" />, then a blank line), <paramref name="unit" /> as built, and a final line feed.
    /// </summary>
    /// <param name="unit">The compilation unit, laid out (<see cref="CompilationUnitOf(MemberDeclarationSyntax)" />), without header trivia.</param>
    /// <param name="pragma">The header's <c>#pragma warning disable</c> line: <see cref="ObsoletePragma" /> unless given.</param>
    public static SourceText Render(CompilationUnitSyntax unit, string? pragma = ObsoletePragma)
    {
        var builder = new StringBuilder(unit.FullSpan.Length + 128);
        builder.Append(pragma is null ? Header + LineFeed : Header + pragma + LineFeed + LineFeed);
        using (var writer = new StringWriter(builder, CultureInfo.InvariantCulture))
        {
            unit.WriteTo(writer);
        }

        builder.Append('\n');
        _types?.Clear();
        _names?.Clear();
        return SourceText.From(builder.ToString(), Encoding.UTF8);
    }

    /// <summary>A compilation unit of one top-level member (a namespace or a type), which starts the file.</summary>
    public static CompilationUnitSyntax CompilationUnitOf(MemberDeclarationSyntax member) =>
        CompilationUnit().WithMembers(SingletonList(Place(member, 0, LineStart(HeadToken(member).LeadingTrivia, 0, blank: false, first: true))));

    /// <summary>A compilation unit of one assembly attribute, <c>[assembly: name(arguments)]</c>.</summary>
    public static CompilationUnitSyntax CompilationUnitOf(string assemblyAttribute, params AttributeArgumentSyntax[] arguments) =>
        CompilationUnit()
           .AddAttributeLists(
                AttributeOf(assemblyAttribute, arguments).WithTarget(AttributeTargetSpecifier(Token(SyntaxKind.AssemblyKeyword), Token(default, SyntaxKind.ColonToken, Spaced)))
            );

    /// <summary><c>namespace name { member }</c>, at the top of the file.</summary>
    public static NamespaceDeclarationSyntax Namespace(string name, MemberDeclarationSyntax member) =>
        NamespaceDeclaration(Qualified(name))
           .WithNamespaceKeyword(Keyword(SyntaxKind.NamespaceKeyword))
           .WithOpenBraceToken(Token(TriviaList(NewLine), SyntaxKind.OpenBraceToken, default))
           .WithMembers(Lines(1, [member]))
           .WithCloseBraceToken(Token(TriviaList(NewLine), SyntaxKind.CloseBraceToken, default));

    /// <summary>A type from its C# text (fully qualified, with nullable annotations), parsed once per file.</summary>
    public static TypeSyntax TypeName(string text)
    {
        var types = _types ??= new(StringComparer.Ordinal);
        if (!types.TryGetValue(text, out var type))
        {
            type = ParseTypeName(text);
            types.Add(text, type);
        }

        return type;
    }

    /// <summary>A name from its C# text (fully qualified), parsed once per file.</summary>
    public static NameSyntax Qualified(string text)
    {
        var names = _names ??= new(StringComparer.Ordinal);
        if (!names.TryGetValue(text, out var name))
        {
            name = ParseName(text);
            names.Add(text, name);
        }

        return name;
    }

    /// <summary>An expression from its C# text: a default value or a service key, which the models hold as C# expressions.</summary>
    public static ExpressionSyntax Code(string text) => ParseExpression(text);

    public static IdentifierNameSyntax Id(string name) => IdentifierName(name);

    public static LiteralExpressionSyntax Number(int value) => LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(value));

    /// <summary>An <c>int</c> constant, negative ones as a unary minus.</summary>
    public static ExpressionSyntax Integer(int value) =>
        value >= 0 ? Number(value) : ParseExpression(value.ToString(CultureInfo.InvariantCulture));

    public static LiteralExpressionSyntax StringLiteral(string value) => LiteralExpression(SyntaxKind.StringLiteralExpression, Literal(value));

    public static LiteralExpressionSyntax DefaultLiteral() => LiteralExpression(SyntaxKind.DefaultLiteralExpression, Token(SyntaxKind.DefaultKeyword));

    public static LiteralExpressionSyntax NullLiteral() => LiteralExpression(SyntaxKind.NullLiteralExpression);

    public static LiteralExpressionSyntax BooleanLiteral(bool value) =>
        LiteralExpression(value ? SyntaxKind.TrueLiteralExpression : SyntaxKind.FalseLiteralExpression);

    /// <summary>The modifiers, each followed by a space.</summary>
    public static SyntaxTokenList Modifiers(params SyntaxKind[] kinds) => TokenList(kinds.Select(Keyword));

    /// <summary><c>int</c>.</summary>
    public static PredefinedTypeSyntax Int() => PredefinedType(Token(SyntaxKind.IntKeyword));

    /// <summary><c>object</c>.</summary>
    public static PredefinedTypeSyntax Object() => PredefinedType(Token(SyntaxKind.ObjectKeyword));

    /// <summary><c>type[]</c>.</summary>
    public static ArrayTypeSyntax ArrayOf(TypeSyntax type) => ArrayType(type, SingletonList(ArrayRankSpecifier()));

    public static MemberAccessExpressionSyntax Member(ExpressionSyntax target, string name) => Member(target, IdentifierName(name));

    public static MemberAccessExpressionSyntax Member(ExpressionSyntax target, SimpleNameSyntax name) =>
        MemberAccessExpression(SyntaxKind.SimpleMemberAccessExpression, target, name);

    public static GenericNameSyntax Generic(string name, params TypeSyntax[] arguments) =>
        GenericName(Identifier(name)).WithTypeArgumentList(TypeArgumentList(Commas(arguments)));

    /// <summary><c>&lt;name&gt;</c>, one type parameter.</summary>
    public static TypeParameterListSyntax TypeParameters(string name) => TypeParameterList(SingletonSeparatedList(TypeParameter(name)));

    public static InvocationExpressionSyntax Invoke(ExpressionSyntax target, params ExpressionSyntax[] arguments) =>
        Invoke(target, arguments.Select(Argument));

    public static InvocationExpressionSyntax Invoke(ExpressionSyntax target, IEnumerable<ArgumentSyntax> arguments) =>
        InvocationExpression(target, ArgumentList(Commas(arguments)));

    /// <summary>A <c>ref</c> argument.</summary>
    public static ArgumentSyntax RefArgument(ExpressionSyntax expression) => Argument(null, Keyword(SyntaxKind.RefKeyword), expression);

    /// <summary>An <c>out var name</c> argument.</summary>
    public static ArgumentSyntax OutVarArgument(string name) =>
        Argument(null, Keyword(SyntaxKind.OutKeyword), DeclarationExpression(VarType(), Designation(name)));

    public static ParameterSyntax Param(TypeSyntax type, string name, ExpressionSyntax? defaultValue = null) =>
        Parameter(default, default, type, Identifier(Spaced, name, default), defaultValue is null ? null : EqualsValueClause(Operator(SyntaxKind.EqualsToken), defaultValue));

    /// <summary>The parameter with an attribute before it, on the same line.</summary>
    public static ParameterSyntax WithAttribute(this ParameterSyntax parameter, AttributeListSyntax attribute) =>
        parameter.AddAttributeLists(attribute.WithCloseBracketToken(Token(default, SyntaxKind.CloseBracketToken, Spaced)));

    /// <summary>A parameter list on one line, <c>(a, b)</c>.</summary>
    public static ParameterListSyntax Params(params ParameterSyntax[] parameters) => ParameterList(Commas(parameters));

    /// <summary>
    ///     A parameter list with one parameter per line when it has more than one, each one level deeper than <paramref name="depth" />, the
    ///     line of the declaration.
    /// </summary>
    public static ParameterListSyntax ParamsPerLine(int depth, params ParameterSyntax[] parameters)
    {
        if (parameters.Length < 2)
        {
            return Params(parameters);
        }

        var line = Line(depth + 1);
        var items = new List<SyntaxNodeOrToken>(parameters.Length * 2 - 1);
        for (var i = 0; i < parameters.Length; i++)
        {
            if (i > 0)
            {
                items.Add(Token(SyntaxKind.CommaToken));
            }

            items.Add(WithFirstTokenLeading(parameters[i], line));
        }

        return ParameterList(SeparatedList<ParameterSyntax>(items));
    }

    /// <summary><c>static name =&gt; body</c>.</summary>
    public static SimpleLambdaExpressionSyntax StaticLambda(string parameter, ExpressionSyntax body) =>
        SimpleLambdaExpression(Parameter(Identifier(parameter)))
           .WithModifiers(Modifiers(SyntaxKind.StaticKeyword))
           .WithArrowToken(Operator(SyntaxKind.EqualsGreaterThanToken))
           .WithExpressionBody(body);

    public static ExpressionStatementSyntax Assign(ExpressionSyntax target, ExpressionSyntax value) =>
        ExpressionStatement(AssignmentExpression(SyntaxKind.SimpleAssignmentExpression, target, Operator(SyntaxKind.EqualsToken), value));

    /// <summary><c>(target ??= value)</c>.</summary>
    public static ParenthesizedExpressionSyntax CoalesceAssign(ExpressionSyntax target, ExpressionSyntax value) =>
        ParenthesizedExpression(AssignmentExpression(SyntaxKind.CoalesceAssignmentExpression, target, Operator(SyntaxKind.QuestionQuestionEqualsToken), value));

    public static ExpressionStatementSyntax Call(ExpressionSyntax target, params ExpressionSyntax[] arguments) => ExpressionStatement(Invoke(target, arguments));

    /// <summary><c>expression;</c>.</summary>
    public static ExpressionStatementSyntax Do(ExpressionSyntax expression) => ExpressionStatement(expression);

    public static ReturnStatementSyntax Return(ExpressionSyntax expression) => ReturnStatement(Keyword(SyntaxKind.ReturnKeyword), expression, Semicolon);

    /// <summary><c>throw expression;</c>.</summary>
    public static ThrowStatementSyntax Throw(ExpressionSyntax expression) => ThrowStatement(default, Keyword(SyntaxKind.ThrowKeyword), expression, Semicolon);

    /// <summary><c>await expression</c>.</summary>
    public static AwaitExpressionSyntax Await(ExpressionSyntax expression) => AwaitExpression(Keyword(SyntaxKind.AwaitKeyword), expression);

    /// <summary><c>typeof(type)</c>.</summary>
    public static TypeOfExpressionSyntax TypeOf(string type) => TypeOfExpression(TypeName(type));

    public static BinaryExpressionSyntax Equal(ExpressionSyntax left, ExpressionSyntax right) => Binary(SyntaxKind.EqualsExpression, SyntaxKind.EqualsEqualsToken, left, right);

    public static BinaryExpressionSyntax NotEqual(ExpressionSyntax left, ExpressionSyntax right) =>
        Binary(SyntaxKind.NotEqualsExpression, SyntaxKind.ExclamationEqualsToken, left, right);

    public static BinaryExpressionSyntax Coalesce(ExpressionSyntax left, ExpressionSyntax right) =>
        Binary(SyntaxKind.CoalesceExpression, SyntaxKind.QuestionQuestionToken, left, right);

    public static BinaryExpressionSyntax Add(ExpressionSyntax left, ExpressionSyntax right) => Binary(SyntaxKind.AddExpression, SyntaxKind.PlusToken, left, right);

    public static BinaryExpressionSyntax LessThan(ExpressionSyntax left, ExpressionSyntax right) => Binary(SyntaxKind.LessThanExpression, SyntaxKind.LessThanToken, left, right);

    /// <summary><c>expression as type</c>.</summary>
    public static BinaryExpressionSyntax As(ExpressionSyntax expression, TypeSyntax type) => Binary(SyntaxKind.AsExpression, SyntaxKind.AsKeyword, expression, type);

    /// <summary><c>!expression</c>.</summary>
    public static PrefixUnaryExpressionSyntax Not(ExpressionSyntax expression) => PrefixUnaryExpression(SyntaxKind.LogicalNotExpression, expression);

    /// <summary><c>condition ? whenTrue : whenFalse</c>.</summary>
    public static ConditionalExpressionSyntax Conditional(ExpressionSyntax condition, ExpressionSyntax whenTrue, ExpressionSyntax whenFalse) =>
        ConditionalExpression(condition, Operator(SyntaxKind.QuestionToken), whenTrue, Operator(SyntaxKind.ColonToken), whenFalse);

    /// <summary><c>expression is pattern</c>.</summary>
    public static IsPatternExpressionSyntax Is(ExpressionSyntax expression, PatternSyntax pattern) => IsPatternExpression(expression, Operator(SyntaxKind.IsKeyword), pattern);

    /// <summary>The pattern <c>type name</c>.</summary>
    public static DeclarationPatternSyntax Declaration(TypeSyntax type, string name) => DeclarationPattern(type, Designation(name));

    /// <summary>The pattern <c>null</c>.</summary>
    public static ConstantPatternSyntax NullPattern() => ConstantPattern(NullLiteral());

    /// <summary>The pattern <c>not null</c>.</summary>
    public static UnaryPatternSyntax NotNullPattern() => UnaryPattern(Keyword(SyntaxKind.NotKeyword), NullPattern());

