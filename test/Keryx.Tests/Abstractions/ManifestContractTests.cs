using Keryx.Analyzers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Rocket.Surgery.Extensions.Testing.SourceGenerators;

namespace Keryx.Tests.Abstractions;

/// <summary>
///     Compiles the manifest attributes exactly as the generator emits them, against the netstandard2.0 <c>Keryx.dll</c> that a contracts or
///     handler library compiles against, then reads them back from compiled metadata the way a host does (by <see cref="KnownTypeNames" />).
/// </summary>
/// <remarks>
///     The named arguments set <c>init</c> properties, which need C# 9. OQ-20 (decided 2026-11-26) keeps them <c>init</c>; Keryx itself
///     requires C# 14 (KRX022). If those properties become <c>set</c>, the C# 8 test fails: update the ADR and the test together.
/// </remarks>
[Timeout(ModuleInitializer.TestTimeout)]
public class ManifestContractTests : GeneratorTest
{
    private const string GeneratedStyleSource = """
        // <auto-generated/>
        #nullable enable
        [assembly: global::Keryx.Internal.KeryxManifest(FormatVersion = 1)]

        namespace Sample
        {
            public sealed class Ping : global::Keryx.INotification { }

            [global::Keryx.BehaviorOrder(global::Keryx.Phase.Validation, Order = 5)]
            public sealed class AuditBehavior { }

            public sealed class LogBehavior<T> { }

            public partial class PingHandler { }

            [global::Keryx.Internal.KeryxHandler(
                typeof(global::Sample.Ping),
                global::Keryx.Internal.HandlerKind.Notification,
                Behaviors = new global::System.Type[] { typeof(global::Sample.LogBehavior<>), typeof(global::Sample.AuditBehavior) },
                Order = 2,
                StaticInvoker = true)]
            public partial class PingHandler { }
        }
        """;

    private static MetadataReference KeryxNetStandard => TestReferences.KeryxNetStandard;

    [Test]
    public async Task Reference_Is_The_NetStandard_Build_Of_Keryx(CancellationToken cancellationToken)
    {
        var compilation = ( await CompileAsync(LanguageVersion.CSharp9, cancellationToken) ).InputCompilation;
        var keryx = (IAssemblySymbol)compilation.GetAssemblyOrModuleSymbol(KeryxNetStandard)!;
        var targetFramework = keryx.GetAttributes()
                                   .Single(static a => a.AttributeClass?.ToDisplayString() == "System.Runtime.Versioning.TargetFrameworkAttribute");

        await Assert.That(keryx.Name).IsEqualTo("Keryx");
        await Assert.That(targetFramework.ConstructorArguments[0].Value).IsEqualTo(".NETStandard,Version=v2.0");
    }

    [Test]
    [Arguments(LanguageVersion.CSharp9)]
    [Arguments(LanguageVersion.Latest)]
    public async Task Generated_Manifest_Compiles_And_Reads_Back_From_Metadata(LanguageVersion languageVersion, CancellationToken cancellationToken)
    {
        var compiled = await CompileAsync(languageVersion, cancellationToken);

        await Assert.That(compiled.FinalDiagnostics.Concat(compiled.EmitDiagnostics).Where(static d => d.Severity >= DiagnosticSeverity.Warning).Select(static d => d.ToString()))
                    .IsEmpty();
        await Assert.That(compiled.EmitResult?.Success).IsTrue();

        // Read the compiled assembly as a host does: as a metadata reference, attributes resolved through KnownTypeNames.
        var host = ( await NetStandardBuilder.WithProjectName("Host").AddCompilationReferences(compiled).Build().GenerateAsync(cancellationToken) ).InputCompilation;
        var assembly = host.References.Select(host.GetAssemblyOrModuleSymbol).OfType<IAssemblySymbol>().Single(static a => a.Name == "Handlers");
        var manifestAttribute = host.GetTypeByMetadataName(KnownTypeNames.KeryxManifestAttribute);
        var handlerAttribute = host.GetTypeByMetadataName(KnownTypeNames.KeryxHandlerAttribute);
        var behaviorOrderAttribute = host.GetTypeByMetadataName(KnownTypeNames.BehaviorOrderAttribute);
        var handlerKind = host.GetTypeByMetadataName(KnownTypeNames.HandlerKind)!;
        var phase = host.GetTypeByMetadataName(KnownTypeNames.Phase)!;

        var manifest = assembly.GetAttributes().Single(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, manifestAttribute));
        await Assert.That(NamedArguments(manifest)).IsEquivalentTo(new Dictionary<string, object?> { ["FormatVersion"] = 1 });

        var handlerType = assembly.GetTypeByMetadataName("Sample.PingHandler")!;
        var handler = handlerType.GetAttributes().Single(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, handlerAttribute));
        await Assert.That(handler.ConstructorArguments.Length).IsEqualTo(2);
        await Assert.That(( (ITypeSymbol)handler.ConstructorArguments[0].Value! ).ToDisplayString()).IsEqualTo("Sample.Ping");
        await Assert.That(SymbolEqualityComparer.Default.Equals(handler.ConstructorArguments[1].Type, handlerKind)).IsTrue();
        await Assert.That(handler.ConstructorArguments[1].Value).IsEqualTo(EnumValue(handlerKind, "Notification"));

        var named = NamedArguments(handler);
        await Assert.That(named.Keys.Order(StringComparer.Ordinal)).IsEquivalentTo(["Behaviors", "Order", "StaticInvoker"]);
        await Assert.That(named["Order"]).IsEqualTo(2);
        await Assert.That((bool?)named["StaticInvoker"]).IsTrue();
        var behaviors = handler.NamedArguments.Single(static a => a.Key == "Behaviors").Value;
        await Assert.That(behaviors.Kind).IsEqualTo(TypedConstantKind.Array);
        await Assert.That(behaviors.Values.Select(static v => ( (ITypeSymbol)v.Value! ).ToDisplayString()))
                    .IsEquivalentTo(["Sample.LogBehavior<>", "Sample.AuditBehavior"], TUnit.Assertions.Enums.CollectionOrdering.Matching);

        var behaviorType = assembly.GetTypeByMetadataName("Sample.AuditBehavior")!;
        var behaviorOrder = behaviorType.GetAttributes()
                                        .Single(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, behaviorOrderAttribute));
        await Assert.That(behaviorOrder.ConstructorArguments[0].Value).IsEqualTo(EnumValue(phase, "Validation"));
        await Assert.That(NamedArguments(behaviorOrder)).IsEquivalentTo(new Dictionary<string, object?> { ["Order"] = 5 });
    }

    [Test]
    public async Task Init_Only_Named_Arguments_Need_CSharp9(CancellationToken cancellationToken)
    {
        var diagnostics = ( await CompileAsync(LanguageVersion.CSharp8, cancellationToken) ).FinalDiagnostics.Where(static d => d.Severity == DiagnosticSeverity.Error).ToArray();

        // FormatVersion, Behaviors, Order, StaticInvoker and BehaviorOrder.Order: each is CS8400 (init-only setters need C# 9).
        await Assert.That(diagnostics.Select(static d => d.Id)).IsEquivalentTo(Enumerable.Repeat("CS8400", 5));
    }

    /// <summary>A netstandard2.0 library: the core framework and the netstandard2.0 Keryx.dll only, with nullable enabled.</summary>
    private GeneratorTestContextBuilder NetStandardBuilder =>
        GeneratorTestContextBuilder.CreateWithoutDefaultReferences()
                                   .WithAssemblyLoadContext(AssemblyLoadContext)
                                   .AddReferences(TestReferences.Framework)
                                   .AddReferences(KeryxNetStandard)
                                   .WithNullableContext(NullableContextOptions.Enable);

    /// <summary>
    ///     The generated-style library. Its project name has no dot: the testing library emits with the project name as the file name, so
    ///     "Sample.Handlers" would emit an assembly named "Sample".
    /// </summary>
    private Task<GeneratorTestResults> CompileAsync(LanguageVersion languageVersion, CancellationToken cancellationToken) =>
        NetStandardBuilder.WithProjectName("Handlers").WithLanguageVersion(languageVersion).AddSources(GeneratedStyleSource).Build().GenerateAsync(cancellationToken);

    private static Dictionary<string, object?> NamedArguments(AttributeData attribute) =>
        attribute.NamedArguments.ToDictionary(static a => a.Key, static a => a.Value.Kind == TypedConstantKind.Array ? null : a.Value.Value);

    private static object? EnumValue(INamedTypeSymbol enumType, string member) =>
        enumType.GetMembers(member).OfType<IFieldSymbol>().Single().ConstantValue;
}
