using Keryx.Analyzers;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static Keryx.Analyzers.GeneratedSyntax;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace Keryx.Tests;

/// <summary>
///     The layout the <see cref="GeneratedSyntax" /> helpers build into the syntax, which <see cref="GeneratedSyntax.Render" /> writes as is
///     (nothing normalizes the whitespace, OQ-66): the spaces within a line, and the lines, indentation and blank lines the containers lay
///     out from the depth they are given (ADR 0001, Incremental generation rules).
/// </summary>
public class GeneratedSyntaxTests
{
    [Test]
    public async Task Render_Adds_The_Header_Last_With_Line_Feeds()
    {
        var text = Rendered(Method(Modifiers(SyntaxKind.PublicKeyword), Id("void"), "M", Params()).Statements(2, []));

        await Assert.That(text).StartsWith("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS0612, CS0618\n\nnamespace Sample\n{\n");
        await Assert.That(text).DoesNotContain("\r");
        await Assert.That(text).EndsWith("        public void M()\n        {\n        }\n    }\n}\n");
    }

    [Test]
    public async Task Render_Writes_Nullable_Types_Without_A_Space_Before_Punctuation()
    {
        var text = Rendered(
            Method(Modifiers(SyntaxKind.PublicKeyword), TypeName("object"), "M", Params(Param(TypeName("int?"), "value")))
               .Expression(2, Cast(TypeName("int?"), Invoke(Id("F"), TypeOf("int?"), Id("value"))))
        );

        await Assert.That(text).Contains("(int? value)");
        await Assert.That(text).Contains("(int?)F(typeof(int?), value)");
        await Assert.That(text).DoesNotContain("? )");
    }

    [Test]
    [Arguments("string?[]")]
    [Arguments("int?[]?")]
    public async Task Render_Writes_Arrays_Of_Nullable_Elements_Without_A_Space_Before_The_Rank(string type)
    {
        var text = Rendered(
            Method(Modifiers(SyntaxKind.PublicKeyword), TypeName($"global::System.Threading.Tasks.ValueTask<{type}>"), "M", Params(Param(TypeName(type), "value")))
               .Expression(2, Invoke(Id("F"), TypeOf(type), Invoke(Generic("G", TypeName(type), TypeName("int")), Id("value"))))
        );

        await Assert.That(text).Contains($"ValueTask<{type}> M({type} value)");
        await Assert.That(text).Contains($"F(typeof({type}), G<{type}, int>(value))");
        await Assert.That(text).DoesNotContain("? [");
        await Assert.That(text).DoesNotContain("? )");
        await Assert.That(text).DoesNotContain("? >");
        await Assert.That(text).DoesNotContain("? ,");
    }

    [Test]
    [Arguments("int[,]")]
    [Arguments("int[][,]")]
    public async Task Render_Writes_A_Multi_Dimensional_Rank_As_Given(string type)
    {
        var text = Rendered(
            Method(Modifiers(SyntaxKind.PublicKeyword), TypeName($"global::System.Threading.Tasks.ValueTask<{type}>"), "M", Params(Param(TypeName(type), "value")))
               .Expression(2, Invoke(Id("F"), TypeOf(type)))
        );

        await Assert.That(text).Contains($"ValueTask<{type}> M({type} value)");
        await Assert.That(text).Contains($"F(typeof({type}))");
        await Assert.That(text).DoesNotContain(", ]");
    }

    [Test]
    public async Task Render_Writes_An_Unbound_Generic_Service_Key_As_Given()
    {
        var text = Rendered(
            Method(Modifiers(SyntaxKind.PublicKeyword), TypeName("object"), "M", Params())
               .Expression(2, Invoke(Id("F"), Code("typeof(global::System.Collections.Generic.Dictionary<,>)")))
        );

        await Assert.That(text).Contains("F(typeof(global::System.Collections.Generic.Dictionary<,>))");
        await Assert.That(text).DoesNotContain(", >");
    }

    [Test]
    public async Task Render_Writes_The_Given_Header_Pragma()
    {
        var unit = CompilationUnitOf(Namespace("Sample", Class(default, "C").WithBody(1, [])));

        await Assert.That(Render(unit).ToString()).StartsWith("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS0612, CS0618\n\n");
        await Assert.That(Render(unit, "#pragma warning disable CS0618").ToString()).StartsWith("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS0618\n\nnamespace Sample\n");
        await Assert.That(Render(unit, pragma: null).ToString()).StartsWith("// <auto-generated/>\n#nullable enable\n\nnamespace Sample\n");
    }

    [Test]
    public async Task Render_Writes_An_Assembly_Attribute_Alone()
    {
        var text = Render(CompilationUnitOf("global::Sample.Marker", Named("Version", Number(1))), pragma: null).ToString();

        await Assert.That(text).IsEqualTo("// <auto-generated/>\n#nullable enable\n\n[assembly: global::Sample.Marker(Version = 1)]\n");
    }

    [Test]
    public async Task Render_Writes_A_Switch_Statement_With_One_Return_Per_Section()
    {
        var text = Rendered(
            Method(Modifiers(SyntaxKind.PublicKeyword), TypeName("int"), "M", Params(Param(TypeName("global::System.Type"), "type")))
               .Statements(
                    2,
                    [
                        Switch(3, Id("type"), [WhenSection(Equal(Id("type"), TypeOf("int")), Return(Number(1))), ConstantSection(2, Return(Number(3)))]),
                        Throw(New(TypeName("global::System.Exception"))),
                    ]
                )
        );

        await Assert.That(text).Contains(
            "            switch (type)\n            {\n                case var _ when type == typeof(int):\n                    return 1;\n                case 2:\n                    return 3;\n            }\n\n            throw new global::System.Exception();\n"
        );
    }

    [Test]
    public async Task Render_Writes_Type_Pattern_And_Default_Sections()
    {
        var text = Rendered(
            Method(Modifiers(SyntaxKind.PublicKeyword), TypeName("int"), "M", Params(Param(TypeName("object"), "value")))
               .Statements(
                    2,
                    [
                        Switch(
                            3,
                            Id("value"),
                            [TypeSection("global::Sample.A", "a", Return(Number(1))), TypeSection("global::Sample.B", null, Return(Number(2))), DefaultSection(Return(Number(0)))]
                        ),
                    ]
                )
        );

        await Assert.That(text).Contains(
            "            switch (value)\n            {\n                case global::Sample.A a:\n                    return 1;\n                case global::Sample.B:\n                    return 2;\n                default:\n                    return 0;\n            }\n        }\n"
        );
    }

    [Test]
    public async Task Render_Separates_A_Statement_That_Ends_With_A_Block_From_The_Next()
    {
        var text = Rendered(
            Method(Modifiers(SyntaxKind.PublicKeyword), Id("void"), "M", Params(Param(TypeName("int"), "value")))
               .Statements(
                    2,
                    [
                        If(3, Equal(Id("value"), Number(0)), [Return(DefaultLiteral())], If(3, LessThan(Id("value"), Number(0)), [Throw(New(TypeName("global::System.Exception")))])),
                        Try(3, [Call(Id("F"))], Catch(3, TypeName("global::System.Exception"), null, [], comment: "// Ignored.")),
                        ForEach(3, "item", Id("items"), [Call(Id("G"), Id("item"))]),
                        Call(Id("H")),
                    ]
                )
        );

        await Assert.That(text).Contains(
            "            if (value == 0)\n            {\n                return default;\n            }\n            else if (value < 0)\n            {\n                throw new global::System.Exception();\n            }\n\n"
          + "            try\n            {\n                F();\n            }\n            catch (global::System.Exception)\n            {\n                // Ignored.\n            }\n\n"
          + "            foreach (var item in items)\n            {\n                G(item);\n            }\n\n            H();\n        }\n"
        );
    }

    [Test]
    public async Task Render_Keeps_The_Space_Before_Is_After_A_Parenthesis()
    {
        var text = Rendered(Method(Modifiers(SyntaxKind.PublicKeyword), TypeName("bool"), "M", Params()).Expression(2, Is(Invoke(Id("F")), Declaration(TypeName("int"), "value"))));

        await Assert.That(text).Contains("F() is int value");
    }

    [Test]
    public async Task Render_Breaks_An_Expression_Body_After_The_Arrow()
    {
        var text = Rendered(Method(Modifiers(SyntaxKind.PublicKeyword), TypeName("int"), "M", Params()).Expression(2, Number(1)));

        await Assert.That(text).Contains("        public int M() =>\n            1;\n");
    }

    [Test]
    public async Task Render_Writes_A_Constraint_Clause_On_Its_Own_Line()
    {
        var text = Rendered(
            Method(Modifiers(SyntaxKind.PublicKeyword), Id("void"), "M", Params(Param(TypeName("T"), "value")))
               .WithTypeParameterList(TypeParameters("T"))
               .Where(2, "T", TypeName("global::Sample.IMarker"))
               .Statements(2, [])
        );

        await Assert.That(text).Contains("        public void M<T>(T value)\n            where T : global::Sample.IMarker\n        {\n        }\n");
    }

    [Test]
    public async Task Render_Writes_The_Parameters_Of_A_Constructor_One_Per_Line_When_There_Is_More_Than_One()
    {
        var text = Rendered(
            Constructor(2, Modifiers(SyntaxKind.PublicKeyword), "C", [Param(TypeName("int"), "value")], [Assign(Id("a"), Id("value"))]),
            Constructor(
                2,
                Modifiers(SyntaxKind.PublicKeyword),
                "C",
                [
                    Param(TypeName("int"), "value").WithAttribute(AttributeOf("global::Sample.Keyed", AttributeArgument(StringLiteral("a")))),
                    Param(TypeName("string"), "name", StringLiteral("b")),
                ],
                []
            )
        );

        await Assert.That(text).Contains("        public C(int value)\n        {\n            a = value;\n        }\n");
        await Assert.That(text).Contains("        public C(\n            [global::Sample.Keyed(\"a\")] int value,\n            string name = \"b\")\n        {\n        }\n");
    }

    [Test]
    public async Task Render_Separates_Members_With_Blank_Lines_But_Not_Plain_Fields()
    {
        var text = Rendered(
            Field(Modifiers(SyntaxKind.PrivateKeyword), TypeName("int"), "a"),
            Field(Modifiers(SyntaxKind.PrivateKeyword), TypeName("int"), "b"),
            Field(Modifiers(SyntaxKind.PrivateKeyword), TypeName("int"), "c").AddAttributeLists(GeneratedCodeAttribute()),
            Method(Modifiers(SyntaxKind.PublicKeyword), TypeName("int"), "M", Params()).Expression(2, Id("a")),
            Method(Modifiers(SyntaxKind.PublicKeyword), TypeName("int"), "N", Params()).Expression(2, Id("b"))
        );

        await Assert.That(text).Contains(
            "        private int a;\n        private int b;\n\n        [global::System.CodeDom.Compiler.GeneratedCode(\"Keryx\", \""
          + GeneratedSyntax.Version
          + "\")]\n        private int c;\n\n        public int M() =>\n            a;\n\n        public int N() =>"
        );
    }

    [Test]
    public async Task Render_Writes_Documentation_Lines_As_Given()
    {
        var text = Rendered(
            Method(Modifiers(SyntaxKind.PublicKeyword), Id("void"), "M", Params())
               .AddAttributeLists(NoInliningAttribute())
               .Statements(2, [])
               .Documented("<summary>", "    See <see cref=\"global::System.Object\" />.", "</summary>")
        );

        await Assert.That(text).Contains(
            "        /// <summary>\n        ///     See <see cref=\"global::System.Object\" />.\n        /// </summary>\n        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]\n        public void M()"
        );
    }

    [Test]
    public async Task Render_Writes_No_Semicolon_After_A_Type_Declaration()
    {
        var text = Rendered(
            Struct(Modifiers(SyntaxKind.PublicKeyword, SyntaxKind.ReadOnlyKeyword), "Inner", Params(Param(TypeName("int"), "value")), "global::Sample.IMarker")
               .WithBody(2, [Field(Modifiers(SyntaxKind.PublicKeyword), TypeName("int"), "Value", Id("value"))])
        );

        await Assert.That(text).DoesNotContain("};");
        await Assert.That(text).Contains("        public readonly struct Inner(int value) : global::Sample.IMarker\n        {\n            public int Value = value;\n        }\n");
    }

    [Test]
    public async Task Render_Writes_A_Nullable_Oblivious_Island_Around_A_Statement_And_An_Expression_Body()
    {
        var text = Rendered(
            Method(Modifiers(SyntaxKind.PublicKeyword), TypeName("int"), "M", Params()).WithBody(Body(2, [Var("x", Number(1)), Return(Id("x"))], nullableIsland: true)),
            Struct(Modifiers(SyntaxKind.PublicKeyword), "Link", null, "global::Sample.IMarker")
               .WithBody(2, [Method(Modifiers(SyntaxKind.PublicKeyword), TypeName("int"), "N", Params()).NullableObliviousExpression(3, Number(1))], restoreNullableWarnings: true)
        );

        await Assert.That(text).Contains("        {\n            var x = 1;\n#nullable disable warnings\n            return x;\n#nullable restore warnings\n        }\n");
        await Assert.That(text).Contains("            public int N() =>\n\n#nullable disable warnings\n            1;\n#nullable restore warnings\n        }\n");
    }

    private static string Rendered(params MemberDeclarationSyntax[] members) =>
        Render(CompilationUnitOf(Namespace("Sample", Class(default, "C").WithBody(1, members)))).ToString();
}
