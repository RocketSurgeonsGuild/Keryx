using Keryx.Analyzers;
using Keryx.Analyzers.Handlers;
using Keryx.Analyzers.Hosts;
using Keryx.Tests.Hosts;
using Microsoft.CodeAnalysis;
using Rocket.Surgery.Extensions.Testing.SourceGenerators;

namespace Keryx.Tests;

/// <summary>
///     The layout every generator writes through <see cref="CodeWriter" /> (ADR 0001, Incremental generation rules): the header, the lines,
///     indentation and blank lines the writer lays out, and, through the generators' output, the shapes the emitters write as text (type
///     names as the models hold them, escaped identifiers and literals).
/// </summary>
public class CodeWriterTests : HostTest
{
    [Test]
    public async Task Writes_The_Header_With_Line_Feeds()
    {
        var text = Written(static writer => Method(writer, "public void M()"));

        await Assert.That(text).StartsWith("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS0612, CS0618\n\nnamespace Sample\n{\n");
        await Assert.That(text).DoesNotContain("\r");
        await Assert.That(text).EndsWith("        public void M()\n        {\n        }\n    }\n}\n");
    }

    [Test]
    public async Task Writes_The_Given_Header_Pragma()
    {
        await Assert.That(new CodeWriter().ToString()).IsEqualTo("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS0612, CS0618\n\n");
        await Assert.That(new CodeWriter("#pragma warning disable CS0618").ToString()).IsEqualTo("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS0618\n\n");
        await Assert.That(new CodeWriter(pragma: null).ToString()).IsEqualTo("// <auto-generated/>\n#nullable enable\n\n");
    }

    [Test]
    public async Task Writes_The_Manifest_As_An_Assembly_Attribute_Alone()
    {
        await Assert.That(HandlerEmitter.Manifest().ToString()).IsEqualTo("// <auto-generated/>\n#nullable enable\n\n[assembly: global::Keryx.Internal.KeryxManifest(FormatVersion = 1)]\n");
    }

    [Test]
    public async Task Writes_A_Switch_Statement_With_One_Statement_Per_Section()
    {
        var text = Written(static writer =>
            {
                writer.Member();
                writer.Line("public int M(object value)");
                writer.Open();
                writer.Switch("value");
                writer.Section("case global::Sample.A a:", "return 1;");
                writer.Section("case global::Sample.B:", "return 2;");
                writer.Section("case var _ when value is int:", "return 3;");
                writer.Section("case 4:", "return 4;");
                writer.Section("default:", "return 0;");
                writer.CloseStatement();
                writer.Line("throw new global::System.Exception();");
                writer.Close();
            }
        );

        await Assert.That(text).Contains(
            "            switch (value)\n            {\n                case global::Sample.A a:\n                    return 1;\n                case global::Sample.B:\n                    return 2;\n"
          + "                case var _ when value is int:\n                    return 3;\n                case 4:\n                    return 4;\n                default:\n                    return 0;\n            }\n\n"
          + "            throw new global::System.Exception();\n        }\n"
        );
    }

    [Test]
    public async Task Separates_A_Statement_That_Ends_With_A_Block_From_The_Next()
    {
        var text = Written(static writer =>
            {
                writer.Member();
                writer.Line("public void M(int value)");
                writer.Open();
                writer.Line("if (value == 0)");
                writer.Open();
                writer.Line("return;");
                writer.Close();
                writer.Line("else if (value < 0)");
                writer.Open();
                writer.Line("throw new global::System.Exception();");
                writer.CloseStatement();
                writer.Line("try");
                writer.Open();
                writer.Line("F();");
                writer.Close();
                writer.Line("catch (global::System.Exception)");
                writer.Open();
                writer.Line("// Ignored.");
                writer.CloseStatement();
                writer.Line("foreach (var item in items)");
                writer.Open();
                writer.Line("G(item);");
                writer.CloseStatement();
                writer.Line("H();");
                writer.Line("if (value > 0)");
                writer.Open();
                writer.Line("I();");
                writer.CloseStatement();
                writer.Close();
            }
        );

        await Assert.That(text).Contains(
            "            if (value == 0)\n            {\n                return;\n            }\n            else if (value < 0)\n            {\n                throw new global::System.Exception();\n            }\n\n"
          + "            try\n            {\n                F();\n            }\n            catch (global::System.Exception)\n            {\n                // Ignored.\n            }\n\n"
          + "            foreach (var item in items)\n            {\n                G(item);\n            }\n\n            H();\n"
          + "            if (value > 0)\n            {\n                I();\n            }\n        }\n"
        );
    }

    [Test]
    public async Task Breaks_An_Expression_Body_After_The_Arrow()
    {
        var text = Written(static writer =>
            {
                writer.Member();
                writer.Arrow("public int M()", "1");
            }
        );

        await Assert.That(text).Contains("        public int M() =>\n            1;\n");
    }

    [Test]
    public async Task Writes_The_Parameters_Of_A_Constructor_One_Per_Line_When_There_Is_More_Than_One()
    {
        var text = Written(static writer =>
            {
                writer.Member();
                writer.Parameters("public C", ["int value"]);
                writer.Open();
                writer.Line("a = value;");
                writer.Close();
                writer.Member();
                writer.Parameters("public C", ["[global::Sample.Keyed(\"a\")] int value", "string name = \"b\""]);
                writer.Open();
                writer.Close();
                writer.Member();
                writer.Parameters("public C", []);
                writer.Open();
                writer.Close();
            }
        );

        await Assert.That(text).Contains("        public C(int value)\n        {\n            a = value;\n        }\n\n");
        await Assert.That(text).Contains("        public C(\n            [global::Sample.Keyed(\"a\")] int value,\n            string name = \"b\")\n        {\n        }\n\n");
        await Assert.That(text).Contains("        public C()\n        {\n        }\n");
    }

    [Test]
    public async Task Separates_Members_With_Blank_Lines_But_Not_Plain_Fields()
    {
        var text = Written(static writer =>
            {
                writer.Member(plainField: true);
                writer.Line("private int a;");
                writer.Member(plainField: true);
                writer.Line("private int b;");
                writer.Member();
                writer.Line(CodeWriter.GeneratedCodeAttribute);
                writer.Line("private int c;");
                writer.Member();
                writer.Arrow("public int M()", "a");
                writer.Member();
                writer.Arrow("public int N()", "b");
                writer.Member(plainField: true);
                writer.Line("private int d;");
            }
        );

        await Assert.That(text).Contains(
            "        private int a;\n        private int b;\n\n        [global::System.CodeDom.Compiler.GeneratedCode(\"Keryx\", \""
          + CodeWriter.Version
          + "\")]\n        private int c;\n\n        public int M() =>\n            a;\n\n        public int N() =>\n            b;\n\n        private int d;\n    }\n"
        );
    }

    [Test]
    public async Task Writes_Documentation_Lines_As_Given_Before_The_Attributes()
    {
        var text = Written(static writer =>
            {
                writer.Member();
                writer.Documentation("<summary>", "    See <see cref=\"global::System.Object\" />.", "</summary>");
                writer.Line(CodeWriter.NoInliningAttribute);
                writer.Line("public void M()");
                writer.Open();
                writer.Close();
                Method(writer, "public void N()");
            }
        );

        await Assert.That(text).Contains(
            "        /// <summary>\n        ///     See <see cref=\"global::System.Object\" />.\n        /// </summary>\n        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]\n        public void M()\n        {\n        }\n\n        public void N()\n"
        );
    }

    [Test]
    public async Task Writes_A_Nested_Type_Without_A_Semicolon_And_Its_Members_One_Level_Deeper()
    {
        var text = Written(static writer =>
            {
                writer.Member();
                writer.Line("public readonly struct Inner(int value) : global::Sample.IMarker");
                writer.Open();
                writer.Member(plainField: true);
                writer.Line("public int Value = value;");
                writer.Close();
            }
        );

        await Assert.That(text).DoesNotContain("};");
        await Assert.That(text).Contains("        public readonly struct Inner(int value) : global::Sample.IMarker\n        {\n            public int Value = value;\n        }\n    }\n}\n");
    }

    [Test]
    public async Task Writes_A_Nullable_Oblivious_Island_Around_A_Statement_And_An_Expression_Body()
    {
        var text = Written(static writer =>
            {
                writer.Member();
                writer.Line("public int M()");
                writer.Open();
                writer.Line("var x = 1;");
                writer.Directive("#nullable disable warnings");
                writer.Line("return x;");
                writer.Directive("#nullable restore warnings");
                writer.Close();
                writer.Member();
                writer.Line("public struct Link : global::Sample.IMarker");
                writer.Open();
                writer.Member();
                writer.NullableObliviousArrow("public int N()", "1");
                writer.Directive("#nullable restore warnings");
                writer.Close();
            }
        );

        await Assert.That(text).Contains("        {\n            var x = 1;\n#nullable disable warnings\n            return x;\n#nullable restore warnings\n        }\n");
        await Assert.That(text).Contains("            public int N() =>\n\n#nullable disable warnings\n            1;\n#nullable restore warnings\n        }\n");
    }

    [Test]
    public async Task Writes_A_Pending_Blank_Line_Before_A_Directive()
    {
        var text = Written(static writer =>
            {
                writer.Member();
                writer.Line("public int M()");
                writer.Open();
                writer.Line("if (a)");
                writer.Open();
                writer.Line("F();");
                writer.CloseStatement();
                writer.Directive("#nullable disable warnings");
                writer.Line("return 1;");
                writer.Directive("#nullable restore warnings");
                writer.Close();
            }
        );

        await Assert.That(text).Contains("            }\n\n#nullable disable warnings\n            return 1;\n#nullable restore warnings\n        }\n");
    }

    /// <summary>
    ///     Type names reach the output as the models hold them, so nullable types and arrays of them have no space before punctuation
    ///     (<c>string?[]</c>, <c>int?[]?</c>, <c>typeof(int?)</c>), a multi-dimensional rank and an unbound generic service key are written as
    ///     declared (<c>int[,]</c>, <c>Dictionary&lt;,&gt;</c>), keywords are <c>@</c>-escaped and string and char keys are escaped literals.
    /// </summary>
    [Test]
    public async Task Writes_Type_Names_Identifiers_And_Literals_As_The_Models_Hold_Them(CancellationToken cancellationToken)
    {
        var result = await HostBuilder.AddSources(Usings + Shapes).Build().GenerateAsync(cancellationToken);

        result.AssertCompilationWasSuccessful(DiagnosticSeverity.Error);
        var mediator = TestSources.HostSource(result, HostEmitter.MediatorHintName);
        var addKeryx = TestSources.HostSource(result, HostEmitter.ServiceCollectionExtensionsHintName);
        var handler = result.Results[typeof(HandlerGenerator)].SyntaxTrees.Single(static t => t.FilePath.Contains("Sample.ShapesHandler.", StringComparison.Ordinal)).ToString();

        foreach (var type in (string[])["string?[]", "int?[]?", "int[,]", "int[][,]"])
        {
            await Assert.That(mediator).Contains($"global::System.Threading.Tasks.ValueTask<{type}>");
        }

        await Assert.That(mediator).Contains("public global::System.Threading.Tasks.ValueTask<int?[]?> Send(global::Sample.NullableValues request, ");
        await Assert.That(mediator).Contains(
            "public global::System.Threading.Tasks.ValueTask Publish<TNotification>(TNotification notification, global::System.Threading.CancellationToken cancellationToken = default)\n            where TNotification : global::Keryx.INotification\n        {\n"
        );
        await Assert.That(addKeryx).Contains("GetRequiredKeyedService<global::Sample.IClock>(serviceProvider, typeof(global::System.Collections.Generic.Dictionary<,>))");
        await Assert.That(addKeryx).Contains("GetRequiredKeyedService<global::Sample.IClock>(serviceProvider, \"a \\\"b\\\"\\\\c\\n\")");
        await Assert.That(addKeryx).Contains("GetRequiredKeyedService<global::Sample.IClock>(serviceProvider, '\\'')");
        await Assert.That(addKeryx).Contains("serviceProvider.GetService(typeof(int?)) is int __value3 ? (int?)__value3 : null");
        await Assert.That(handler).Contains("[global::Microsoft.Extensions.DependencyInjection.FromKeyedServicesAttribute(typeof(global::System.Collections.Generic.Dictionary<,>))] global::Sample.IClock unbound,");
        await Assert.That(handler).Contains("            int? @class = null)\n");
        await Assert.That(handler).Contains("            __keryx_class = @class;\n");
        foreach (var text in (string[])[mediator, addKeryx, handler])
        {
            await Assert.That(text).DoesNotContain("? [");
            await Assert.That(text).DoesNotContain("? )");
            await Assert.That(text).DoesNotContain("? >");
            await Assert.That(text).DoesNotContain(", ]");
            await Assert.That(text).DoesNotContain(", >");
            await Assert.That(text).DoesNotContain("};");
            await Assert.That(text).DoesNotContain("\r");
        }
    }

    private const string Shapes = """
        namespace Sample
        {
            public interface IClock { }

            public sealed record Nullables(int Id) : IRequest<string?[]>;
            public static partial class NullablesHandler { private static string?[] Handle(Nullables request) => []; }

            public sealed record NullableValues(int Id) : IRequest<int?[]?>;
            public static partial class NullableValuesHandler { private static int?[]? Handle(NullableValues request) => null; }

            public sealed record Grid(int Id) : IRequest<int[,]>;
            public static partial class GridHandler { private static int[,] Handle(Grid request) => new int[1, 1]; }

            public sealed record Jagged(int Id) : IRequest<int[][,]>;
            public static partial class JaggedHandler { private static int[][,] Handle(Jagged request) => []; }

            public sealed record Shapes(int Id) : IRequest<int>;
            public partial class ShapesHandler
            {
                private static int Handle(
                    Shapes request,
                    [FromKeyedServices(typeof(Dictionary<,>))] IClock unbound,
                    [FromKeyedServices("a \"b\"\\c\n")] IClock quoted,
                    [FromKeyedServices('\'')] IClock character,
                    int? @class = null) => 1;
            }
        }
        """;

    private static void Method(CodeWriter writer, string declaration)
    {
        writer.Member();
        writer.Line(declaration);
        writer.Open();
        writer.Close();
    }

    /// <summary>A file with the members <paramref name="members" /> writes in <c>class C</c> in <c>namespace Sample</c>.</summary>
    private static string Written(Action<CodeWriter> members)
    {
        var writer = new CodeWriter();
        writer.Namespace("Sample");
        writer.Member();
        writer.Line("class C");
        writer.Open();
        members(writer);
        writer.Close();
        writer.Close();
        return writer.ToSourceText().ToString();
    }
