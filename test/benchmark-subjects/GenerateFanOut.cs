// One constructor parameter per line, the last without a comma.
static void Parameters(Writer w, int count, Func<int, string> parameter)
{
    for (var i = 1; i <= count; i++)
    {
        w.Line("    " + parameter(i) + (i < count ? "," : ""));
    }
}

static string FindRepositoryRoot(string start)
{
    for (var directory = new DirectoryInfo(start); directory is not null; directory = directory.Parent)
    {
        if (File.Exists(Path.Combine(directory.FullName, "Keryx.slnx")))
        {
            return directory.FullName;
        }
    }

    throw new InvalidOperationException($"No Keryx.slnx in {start} or above it: run the script from inside the repository.");
}

/// <summary>C# text with four-space indentation and LF line ends, as the repository's formatter leaves it.</summary>
internal sealed class Writer
{
    private readonly StringBuilder _text = new(1 << 20);
    private int _depth;

    public void Raw(string text) => _text.Append(text.ReplaceLineEndings("\n"));

    public void Line(string line) => _text.Append(' ', _depth * 4).Append(line).Append('\n');

    public void Blank() => _text.Append('\n');

    public void Open()
    {
        Line("{");
        _depth++;
    }

    public void Close()
    {
        _depth--;
        Line("}");
    }

    public override string ToString() => _text.ToString();
}
