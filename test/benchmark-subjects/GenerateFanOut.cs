// Writes the fan-out benchmark subjects (owner decision 41): the notifications with 25, 50 and 100 handlers, in a project of their own per
// library (test/benchmark-subjects/Keryx.Benchmarks.FanOut.*), and the comparison scenarios that publish them
// (test/Keryx.Benchmarks/Comparison/FanOutBenchmarks.cs). Every subject gets the same handler bodies (PingedWork's, or the probe hit of the
// sync publish), written from the same lists here, so the libraries are compared on identical work. Run it from anywhere in the repository
// after changing it, and commit what it writes:
//   dotnet run --file test/benchmark-subjects/GenerateFanOut.cs
// With --check it writes nothing and fails when a file differs from what it would write (CI's benchmark Dry job runs it that way).
using System.Text;

int[] sizes = [25, 50, 100];
var check = args is ["--check"];
if (args.Length > 0 && !check)
{
    Console.Error.WriteLine("Usage: dotnet run --file test/benchmark-subjects/GenerateFanOut.cs [-- --check]");
    return 2;
}

var root = FindRepositoryRoot(Environment.CurrentDirectory);
var subjects = Path.Combine(root, "test", "benchmark-subjects");
var outputs = new (string Path, string Text)[]
{
    (Path.Combine(subjects, "Keryx.Benchmarks.FanOut.Baseline", "FanOut.cs"), Baseline(sizes)),
    (Path.Combine(subjects, "Keryx.Benchmarks.FanOut.KeryxHost", "FanOut.cs"), KeryxHost(sizes)),
    (Path.Combine(subjects, "Keryx.Benchmarks.FanOut.MediatorScoped", "FanOut.cs"), Mediator(sizes, "MediatorScoped", "Scoped", typical: true, sync: true)),
    (Path.Combine(subjects, "Keryx.Benchmarks.FanOut.MediatorSingleton", "FanOut.cs"), Mediator(sizes, "MediatorSingleton", "Singleton", typical: false, sync: true)),
    (Path.Combine(subjects, "Keryx.Benchmarks.FanOut.MediatorParallel", "FanOut.cs"), Mediator(sizes, "MediatorParallel", "Singleton", typical: false, sync: false)),
    (Path.Combine(subjects, "Keryx.Benchmarks.FanOut.MediatRHandlers", "FanOut.cs"), MediatR(sizes)),
    (Path.Combine(subjects, "Keryx.Benchmarks.FanOut.ZeroAllocMediator", "FanOut.cs"), ZeroAlloc(sizes)),
    (Path.Combine(root, "test", "Keryx.Benchmarks", "Comparison", "FanOutBenchmarks.cs"), Benchmarks(sizes)),
};

var stale = 0;
foreach (var (path, text) in outputs)
{
    var relative = Path.GetRelativePath(root, path);
    var current = File.Exists(path) ? File.ReadAllText(path) : null;
    if (current == text)
    {
        continue;
    }

    stale++;
    if (check)
    {
        Console.Error.WriteLine($"{relative} differs from what GenerateFanOut.cs writes; run the script and commit the result.");
        continue;
    }

    Directory.CreateDirectory(Path.GetDirectoryName(path)!);
    File.WriteAllText(path, text, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
    Console.WriteLine($"Wrote {relative}");
}

if (stale == 0)
{
    Console.WriteLine("The fan-out files are up to date.");
}

return check && stale > 0 ? 1 : 0;

// The handler's suffix: Handler001 to Handler100, so the names sort in call order.
static string Handler(int i) => $"Handler{i:D3}";

static string Header(string what) =>
    $"""
    // Generated by test/benchmark-subjects/GenerateFanOut.cs (owner decision 41); do not edit. Change the script and run it again:
    //   dotnet run --file test/benchmark-subjects/GenerateFanOut.cs
    // {what}

    """;

static string Baseline(int[] sizes)
{
    var w = new Writer();
    w.Raw(
        Header(
            "The direct-call baseline of the fan-out scenarios: the sync publish's handlers as static methods called in turn, and the real-world\n"
          + "// handlers as scoped classes a hand-written publisher class (scoped) takes in its constructor and calls in turn, as Baseline/RealWorldPublish.cs\n"
          + "// does for 1 and 5 handlers."
        )
    );
    w.Line("using Keryx.Benchmarks.Common;");
    w.Line("using Microsoft.Data.Sqlite;");
    w.Line("using Microsoft.Extensions.DependencyInjection;");
    w.Line("using Microsoft.Extensions.Logging;");
    w.Blank();
    w.Line("namespace Keryx.Benchmarks.FanOut.Baseline;");
    w.Blank();
    foreach (var family in (string[])["Pinged", "TypicalPinged", "QueryPinged"])
    {
        foreach (var n in sizes)
        {
            w.Line($"public sealed record {family}{n}({(family == "Pinged" ? "int Value" : "int Id")});");
        }
    }

    w.Blank();
    w.Line("/// <summary>The sync publish's handlers and publishers, called directly (Baseline/Handlers.cs does the same for 1 and 5 handlers).</summary>");
    w.Line("public static class Handlers");
    w.Open();
    var first = true;
    foreach (var n in sizes)
    {
        for (var i = 1; i <= n; i++)
        {
            if (!first)
            {
                w.Blank();
            }

            first = false;
            w.Line($"public static ValueTask Handle{i:D3}(Pinged{n} notification)");
            w.Open();
            w.Line("Probe.Hit();");
            w.Line("return default;");
            w.Close();
        }

        w.Blank();
        w.Line("/// <summary>");
        w.Line($"///     Calls each handler of <see cref=\"Pinged{n}\" /> in turn, as a sequential publish does. Not async: while the handlers complete");
        w.Line("///     synchronously it runs no state machine, so it stays the floor; <c>PublishSlow</c> takes over from the first one that does not.");
        w.Line("/// </summary>");
        w.Line($"public static ValueTask Publish(Pinged{n} notification)");
        w.Open();
        for (var i = 1; i <= n; i++)
        {
            if (i > 1)
            {
                w.Blank();
            }

            w.Line($"var h{i:D3} = Handle{i:D3}(notification);");
            w.Line($"if (!h{i:D3}.IsCompletedSuccessfully)");
            w.Open();
            w.Line($"return PublishSlow(h{i:D3}, notification, {i});");
            w.Close();
            w.Blank();
            w.Line($"h{i:D3}.GetAwaiter().GetResult();");
        }

        w.Line("return default;");
        w.Close();
        w.Blank();
        w.Line("/// <summary>Awaits the pending handler, then runs the handlers after it (<paramref name=\"next\" /> is the 0-based index of the next one).</summary>");
        w.Line($"private static async ValueTask PublishSlow(ValueTask pending, Pinged{n} notification, int next)");
        w.Open();
        w.Line("await pending;");
        for (var i = 2; i <= n; i++)
        {
            w.Line($"if (next <= {i - 1})");
            w.Open();
            w.Line($"await Handle{i:D3}(notification);");
            w.Close();
            if (i < n)
            {
                w.Blank();
            }
        }

        w.Close();
    }

    w.Close();
    foreach (var n in sizes)
    {
        for (var i = 1; i <= n; i++)
        {
            w.Blank();
            w.Line($"public sealed class TypicalPinged{n}{Handler(i)}(IPongRepository repository, ILogger<TypicalPinged{n}> logger)");
            w.Open();
            w.Line($"public ValueTask Handle(TypicalPinged{n} notification) => PingedWork.Lookup(notification.Id, repository, logger);");
            w.Close();
        }
    }

    foreach (var n in sizes)
    {
        w.Blank();
        w.Line($"/// <summary>Calls the {n} handlers of <see cref=\"TypicalPinged{n}\" /> in turn.</summary>");
        w.Line($"public sealed class TypicalPinged{n}Publisher(");
        Parameters(w, n, i => $"TypicalPinged{n}{Handler(i)} h{i:D3}");
        w.Line(")");
        w.Open();
        w.Line($"public async ValueTask Publish(TypicalPinged{n} notification)");
        w.Open();
        for (var i = 1; i <= n; i++)
        {
            w.Line($"await h{i:D3}.Handle(notification).ConfigureAwait(false);");
        }

        w.Close();
        w.Close();
    }

    foreach (var n in sizes)
    {
        w.Blank();
        w.Line($"/// <summary><see cref=\"TypicalPinged{n}Publisher\" /> with the notification logging behavior's two messages written inline.</summary>");
        w.Line($"public sealed class LoggedPinged{n}Publisher(");
        Parameters(w, n + 1, i => i <= n ? $"TypicalPinged{n}{Handler(i)} h{i:D3}" : $"ILogger<TypicalPinged{n}> logger");
        w.Line(")");
        w.Open();
        w.Line($"public async ValueTask Publish(TypicalPinged{n} notification)");
        w.Open();
        w.Line($"RequestLog.Publishing(logger, MessageName<TypicalPinged{n}>.Value);");
        for (var i = 1; i <= n; i++)
        {
            w.Line($"await h{i:D3}.Handle(notification).ConfigureAwait(false);");
        }

        w.Line($"RequestLog.Published(logger, MessageName<TypicalPinged{n}>.Value);");
        w.Close();
        w.Close();
    }

    foreach (var n in sizes)
    {
        for (var i = 1; i <= n; i++)
        {
            w.Blank();
            w.Line($"public sealed class QueryPinged{n}{Handler(i)}(SqliteConnection connection, ILogger<QueryPinged{n}> logger)");
            w.Open();
            w.Line($"public ValueTask Handle(QueryPinged{n} notification, CancellationToken cancellationToken = default) =>");
            w.Line("    PingedWork.QueryAsync(notification.Id, connection, logger, cancellationToken);");
            w.Close();
        }
    }

    foreach (var n in sizes)
    {
        w.Blank();
        w.Line($"/// <summary>Awaits the {n} handlers of <see cref=\"QueryPinged{n}\" /> in turn, or starts all {n} before awaiting any.</summary>");
        w.Line($"public sealed class QueryPinged{n}Publisher(");
        Parameters(w, n, i => $"QueryPinged{n}{Handler(i)} h{i:D3}");
        w.Line(")");
        w.Open();
        w.Line($"public async ValueTask Publish(QueryPinged{n} notification)");
        w.Open();
        for (var i = 1; i <= n; i++)
        {
            w.Line($"await h{i:D3}.Handle(notification).ConfigureAwait(false);");
        }

        w.Close();
        w.Blank();
        w.Line($"public async ValueTask PublishParallel(QueryPinged{n} notification)");
        w.Open();
        for (var i = 1; i <= n; i++)
        {
            w.Line($"var t{i:D3} = h{i:D3}.Handle(notification);");
        }

        for (var i = 1; i <= n; i++)
        {
            w.Line($"await t{i:D3}.ConfigureAwait(false);");
        }

        w.Close();
        w.Close();
    }

    w.Blank();
    w.Line("/// <summary>Registers the fan-out baseline's handlers and publishers, all scoped, and the shared real-world services.</summary>");
    w.Line("public static class BaselineFanOutSetup");
    w.Open();
    w.Line("public static IServiceCollection AddBaselineFanOutBenchmarks(this IServiceCollection services)");
    w.Open();
    w.Line("services.AddRealWorldServices();");
    foreach (var n in sizes)
    {
        for (var i = 1; i <= n; i++)
        {
            w.Line($"services.AddScoped<TypicalPinged{n}{Handler(i)}>();");
        }

        w.Line($"services.AddScoped<TypicalPinged{n}Publisher>();");
        w.Line($"services.AddScoped<LoggedPinged{n}Publisher>();");
        for (var i = 1; i <= n; i++)
        {
            w.Line($"services.AddScoped<QueryPinged{n}{Handler(i)}>();");
        }

        w.Line($"services.AddScoped<QueryPinged{n}Publisher>();");
    }

    w.Line("return services;");
    w.Close();
    w.Close();
    return w.ToString();
}

