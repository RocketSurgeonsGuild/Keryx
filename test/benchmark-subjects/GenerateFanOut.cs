    w.Open();
    w.Line("public static IServiceCollection AddKeryxFanOutBenchmarks(this IServiceCollection services)");
    w.Open();
    w.Line("services.AddRealWorldServices();");
    w.Line("return services.AddKeryx();");
    w.Close();
    w.Close();
    return w.ToString();
}

// Mediator (martinothamar): one project per configuration, because the generator reads the lifetime and the notification publisher from the
// AddMediator call at compile time, so they are fixed per assembly.
static string Mediator(int[] sizes, string project, string lifetime, bool typical, bool sync)
{
    var w = new Writer();
    var what = project switch
    {
        "MediatorScoped" => "Mediator with the scoped lifetime: the sync publish's handlers, TypicalPinged's (published with a scope per request) and\n"
          + "// QueryPinged's (published sequentially, Mediator's default ForeachAwaitPublisher), as Keryx.Benchmarks.MediatorScoped has them for 1 and 5\n"
          + "// handlers.",
        "MediatorSingleton" => "Mediator with the singleton lifetime: the sync publish's handlers and QueryPinged's (published sequentially, Mediator's\n"
          + "// default ForeachAwaitPublisher), as Keryx.Benchmarks.MediatorSingleton has them for 1 and 5 handlers; no TypicalPinged, whose handlers take\n"
          + "// the scoped repository (open-questions OQ-72).",
        _ => "Mediator with the singleton lifetime and its TaskWhenAllPublisher: QueryPinged's handlers, for the parallel publish, as\n"
          + "// Keryx.Benchmarks.MediatorParallel has them for 1 and 5 handlers.",
    };
    w.Raw(Header(what));
    w.Line("using Keryx.Benchmarks.Common;");
    w.Line("using Mediator;");
    w.Line("using Microsoft.Data.Sqlite;");
    w.Line("using Microsoft.Extensions.DependencyInjection;");
    w.Line("using Microsoft.Extensions.Logging;");
    w.Blank();
    w.Line($"namespace Keryx.Benchmarks.FanOut.{project};");
    var families = new List<string>();
    if (sync)
    {
        families.Add("Pinged");
    }

    if (typical)
    {
        families.Add("TypicalPinged");
    }

    families.Add("QueryPinged");
    foreach (var family in families)
    {
        foreach (var n in sizes)
        {
            w.Blank();
            w.Line($"public sealed record {family}{n}({(family == "Pinged" ? "int Value" : "int Id")}) : INotification;");
        }
    }

    foreach (var family in families)
    {
        foreach (var n in sizes)
        {
            for (var i = 1; i <= n; i++)
            {
                w.Blank();
                switch (family)
                {
                    case "Pinged":
                        w.Line($"public sealed class Pinged{n}{Handler(i)} : INotificationHandler<Pinged{n}>");
                        w.Open();
                        w.Line($"public ValueTask Handle(Pinged{n} notification, CancellationToken cancellationToken)");
                        w.Open();
                        w.Line("Probe.Hit();");
                        w.Line("return default;");
                        w.Close();
                        w.Close();
                        break;
                    case "TypicalPinged":
                        w.Line(
                            $"public sealed class TypicalPinged{n}{Handler(i)}(IPongRepository repository, ILogger<TypicalPinged{n}> logger) : INotificationHandler<TypicalPinged{n}>"
                        );
                        w.Open();
                        w.Line($"public ValueTask Handle(TypicalPinged{n} notification, CancellationToken cancellationToken) =>");
                        w.Line("    PingedWork.Lookup(notification.Id, repository, logger);");
                        w.Close();
                        break;
                    default:
                        w.Line(
                            $"public sealed class QueryPinged{n}{Handler(i)}(SqliteConnection connection, ILogger<QueryPinged{n}> logger) : INotificationHandler<QueryPinged{n}>"
                        );
                        w.Open();
                        w.Line($"public ValueTask Handle(QueryPinged{n} notification, CancellationToken cancellationToken) =>");
                        w.Line("    PingedWork.QueryAsync(notification.Id, connection, logger, cancellationToken);");
                        w.Close();
                        break;
                }
            }
        }
    }

    var publisher = sync ? "" : " and Mediator's <see cref=\"TaskWhenAllPublisher\" />";
    w.Blank();
    w.Line($"/// <summary>Registers this assembly's generated mediator with the {lifetime.ToLowerInvariant()} lifetime{publisher}, and the real-world services.</summary>");
    w.Line($"public static class {project}FanOutSetup");
    w.Open();
    w.Line($"public static IServiceCollection Add{project}FanOutBenchmarks(this IServiceCollection services)");
    w.Open();
    w.Line("services.AddRealWorldServices();");
    w.Line("// The generator reads these options from this call at compile time.");
    w.Line("return services.AddMediator(");
    w.Line("    static (MediatorOptions options) =>");
    w.Line("    {");
    w.Line($"        options.Namespace = \"Keryx.Benchmarks.FanOut.{project}\";");
    w.Line($"        options.ServiceLifetime = ServiceLifetime.{lifetime};");
    if (!sync)
    {
        w.Line("        options.NotificationPublisherType = typeof(TaskWhenAllPublisher);");
    }

    w.Line("    }");
    w.Line(");");
    w.Close();
    w.Close();
    return w.ToString();
}

